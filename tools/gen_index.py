#!/usr/bin/env python3
"""Generate docs/TASK-INDEX.md — master index of all 998 tasks with solution status."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_tasks import LANG_FILES, LANGS, TIER_LABELS, TIERS, parse_readme, slugify  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    tasks = parse_readme()
    mapping = json.loads((ROOT / "docs" / "ctci-mapping.json").read_text(encoding="utf-8"))

    rows = []
    done = {lang: 0 for lang in LANGS}
    done_by_tier: dict[str, int] = {t: 0 for t in TIERS}
    tutorials = 0
    for t in tasks:
        num, tier, title = t["number"], t["tier"], t["title"]
        slug = slugify(title)
        flags = {}
        all_done = True
        for lang in LANGS:
            ok = (ROOT / "solutions" / lang / tier / f"{num:03d}-{slug}" / LANG_FILES[lang]).exists()
            flags[lang] = "✅" if ok else "—"
            if ok:
                done[lang] += 1
            else:
                all_done = False
        if all_done:
            done_by_tier[tier] += 1
        spec = f"../tasks/{tier}/{num:03d}-{slug}.md"
        chapter = mapping.get(str(num), "—")
        tutorial_path = ROOT / "tutorials" / "tasks" / tier / f"{num:03d}-{slug}.md"
        if tutorial_path.exists():
            tutorials += 1
            tutorial = f"[📘](../tutorials/tasks/{tier}/{num:03d}-{slug}.md)"
        else:
            tutorial = "—"
        rows.append(f"| [{num:03d}]({spec}) | {title} | {TIER_LABELS[tier]} | {chapter} | "
                    f"{flags['python']} | {flags['java']} | {flags['javascript']} | {flags['csharp']} | "
                    f"{tutorial} |")

    lines = [
        "# Task Index — all 998 tasks",
        "",
        "Master index generated by [`tools/gen_index.py`](../tools/gen_index.py). "
        "Click a task number to open its spec; ✅ marks an implemented solution in that language, "
        "📘 marks a step-by-step tutorial in [`tutorials/tasks/`](../tutorials/tasks).",
        "",
        "## Progress",
        "",
        "| Language | Implemented |",
        "|---|---|",
    ]
    for lang in LANGS:
        lines.append(f"| {lang.capitalize()} | {done[lang]} / 998 |")
    lines += ["", "| Tier | Fully implemented (4/4 languages) |", "|---|---|"]
    for tier in TIERS:
        lines.append(f"| {TIER_LABELS[tier]} | {done_by_tier[tier]} / {sum(1 for t in tasks if t['tier'] == tier)} |")
    lines += ["", "## Tasks", "",
              "| # | Title | Tier | CTCI chapter | Python | Java | JS | C# | Tutorial |",
              "|---|-------|------|--------------|--------|------|----|----|----------|"]
    lines.extend(rows)
    lines.append("")
    (ROOT / "docs" / "TASK-INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote docs/TASK-INDEX.md ({len(rows)} rows)")
    for lang in LANGS:
        print(f"  {lang}: {done[lang]}/998")
    print(f"  tutorials: {tutorials}/998")


if __name__ == "__main__":
    main()

// Task 560 - Implement Berlekamp–Massey for minimal linear recurrence (conceptual). (Tier: Advanced, CTCI Beyond — Advanced Data Structures & Algorithms)
//
// Berlekamp–Massey over the prime field F_p with p = 1e9+7, implemented in full rather than described.
// The connection polynomial c(x) = 1 + c_1 x + ... + c_L x^L starts as 1, and for each new term the
// discrepancy d = sum_i c_i s_{n-i} is computed; when d is non-zero and 2L <= n the algorithm updates
// the length to L = n + 1 - L and rewrites c(x) := c(x) - (d/bb) x^m b(x) using the saved previous
// polynomial b(x), otherwise it only performs the correction step. Divisions use the extended
// Euclidean inverse modulo p, so the algorithm works in any prime field (a separate run with p = 97
// and a run over GF(2) = F_2 demonstrate this). The output is converted to the usual recurrence form
// s_n = c_1 s_{n-1} + ... + c_L s_{n-L}, and the file verifies both that the recurrence reproduces
// every given term (and terms beyond the input window, when the input is long enough) and that no
// shorter recurrence fits. Minimality is checked by exhaustively trying every candidate recurrence of
// lower order over the small field F_97, which is feasible there and therefore a genuine proof for
// those instances; over the large field the check is by the algorithm's own theory plus reproduction
// tests. The documented caveat is included: with fewer than 2L terms the data cannot determine the true
// order, so BM returns the shortest polynomial consistent with the data seen, which can fail to predict
// later terms - asserted explicitly on a 2-term prefix of an order-3 sequence. No randomness is used
// at all: every sequence is either a closed form, an LFSR, or a splitmix64-derived deterministic one.
//
// Documented checks: Fibonacci modulo p gives order 2 with coefficients (1,1), 5^n gives order 1 with
// coefficient 5, and s_n = n gives order 2 with coefficients (2, p-1); the all-zero sequence gives
// order 0 and a constant sequence order 1; a splitmix64-seeded LFSR of order 5 is recovered exactly
// from 2L = 10 terms, the found recurrence predicts the next 10 terms, and adding more terms does not
// reduce the recovered order; the GF(2) sequence generated by x^4 + x + 1 (taps 4 and 1) is recovered
// with order 4 and its period is exactly 15; over F_97, exhaustive search confirms that no order-1 and
// no order-2 recurrence fits an order-3 LFSR sequence (only the true order 3 does, and BM returns it);
// and the short-prefix caveat is exhibited on an order-2 sequence over F_97 whose two-term prefix also
// satisfies an order-1 recurrence, which then mispredicts the third term.
using System;
using System.Collections.Generic;

internal static class SplitMix64
{
    /** splitmix64 (Steele/Lea/Flood): 64-bit state advanced by a golden-ratio increment. */
    internal static ulong Next(ref ulong state)
    {
        state += 0x9E3779B97F4A7C15UL;
        ulong z = state;
        z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9UL;
        z = (z ^ (z >> 27)) * 0x94D049BB133111EBUL;
        return z ^ (z >> 31);
    }
}

internal static class BerlekampMassey
{
    /** Returns c_1..c_L with s_n = c_1 s_{n-1} + ... + c_L s_{n-L} (mod p) for the minimal L. */
    internal static long[] Find(long[] s, long p)
    {
        int n = s.Length;
        var c = new long[n + 1];
        var b = new long[n + 1];
        c[0] = 1;
        b[0] = 1;
        int l = 0;
        int m = 1;
        long bb = 1;
        for (int step = 0; step < n; step++)
        {
            long d = 0;
            for (int i = 0; i <= l; i++) d = (d + c[i] * s[step - i]) % p;
            d = ((d % p) + p) % p;
            if (d == 0)
            {
                m++;
                continue;
            }
            long coef = d % p * ModInverse(bb, p) % p;
            var previous = (long[])c.Clone();
            if (2 * l <= step)
            {
                for (int i = 0; i + m <= n; i++)
                {
                    c[i + m] = ((c[i + m] - coef * b[i]) % p + p) % p;
                }
                l = step + 1 - l;
                b = previous;
                bb = d;
                m = 1;
            }
            else
            {
                for (int i = 0; i + m <= n; i++)
                {
                    c[i + m] = ((c[i + m] - coef * b[i]) % p + p) % p;
                }
                m++;
            }
        }
        var coeffs = new long[l];
        for (int i = 0; i < l; i++) coeffs[i] = ((p - c[i + 1]) % p + p) % p;
        return coeffs;
    }

    internal static long ModInverse(long a, long p)
    {
        long t = 0;
        long newT = 1;
        long r = p;
        long newR = ((a % p) + p) % p;
        while (newR != 0)
        {
            long q = r / newR;
            long temp = t - q * newT;
            t = newT;
            newT = temp;
            long tempR = r - q * newR;
            r = newR;
            newR = tempR;
        }
        if (r != 1) throw new Exception("value is not invertible modulo p");
        return ((t % p) + p) % p;
    }

    /** Does the recurrence reproduce s[from..] ? */
    internal static bool Satisfies(long[] s, long[] coeffs, long p, int from)
    {
        int l = coeffs.Length;
        if (l == 0)
        {
            for (int i = from; i < s.Length; i++)
            {
                if (s[i] % p != 0) return false;
            }
            return true;
        }
        for (int i = Math.Max(from, l); i < s.Length; i++)
        {
            long value = 0;
            for (int j = 0; j < l; j++) value = (value + coeffs[j] * s[i - 1 - j]) % p;
            if (((value % p) + p) % p != s[i]) return false;
        }
        return true;
    }

    /** Extends a sequence with its own recurrence. */
    internal static long[] Extend(long[] s, long[] coeffs, long p, int length)
    {
        var result = new List<long>(s);
        int l = coeffs.Length;
        while (result.Count < length)
        {
            long value = 0;
            for (int j = 0; j < l; j++) value = (value + coeffs[j] * result[result.Count - 1 - j]) % p;
            result.Add(((value % p) + p) % p);
        }
        return result.ToArray();
    }

    /** Exhaustive search over all recurrences of the given order in F_p (tiny p only). */
    internal static bool AnyOfOrder(long[] s, long p, int order)
    {
        var coeffs = new long[order];
        return Search(s, p, order, 0, coeffs);
    }

    private static bool Search(long[] s, long p, int order, int depth, long[] coeffs)
    {
        if (depth == order) return Satisfies(s, coeffs, p, order);
        for (int v = 0; v < p; v++)
        {
            coeffs[depth] = v;
            if (Search(s, p, order, depth + 1, coeffs)) return true;
        }
        return false;
    }
}

public static class Solution
{
    public static void Main()
    {
        const long P = 1000000007L;

        // Closed-form sequences.
        long[] fibonacci = new long[40];
        fibonacci[0] = 0;
        fibonacci[1] = 1;
        for (int i = 2; i < fibonacci.Length; i++) fibonacci[i] = fibonacci[i - 1] + fibonacci[i - 2];
        long[] fibCoeffs = BerlekampMassey.Find(fibonacci, P);
        Check(fibCoeffs.Length == 2, "Fibonacci modulo p has order 2, got " + fibCoeffs.Length);
        Check(fibCoeffs[0] == 1 && fibCoeffs[1] == 1, "Fibonacci coefficients are (1,1)");
        Check(BerlekampMassey.Satisfies(fibonacci, fibCoeffs, P, 0), "the recurrence reproduces Fibonacci");

        long[] geometric = new long[20];
        long power = 1;
        for (int i = 0; i < geometric.Length; i++)
        {
            geometric[i] = power;
            power = power * 5 % P;
        }
        long[] geometricCoeffs = BerlekampMassey.Find(geometric, P);
        Check(geometricCoeffs.Length == 1 && geometricCoeffs[0] == 5, "5^n has order 1 with coefficient 5");
        Check(BerlekampMassey.Satisfies(geometric, geometricCoeffs, P, 0), "5^n is reproduced");

        long[] identity = new long[20];
        for (int i = 0; i < identity.Length; i++) identity[i] = i % P;
        long[] identityCoeffs = BerlekampMassey.Find(identity, P);
        Check(identityCoeffs.Length == 2 && identityCoeffs[0] == 2 && identityCoeffs[1] == P - 1,
                "s_n = n has order 2 with coefficients (2, p-1)");
        Check(BerlekampMassey.Satisfies(identity, identityCoeffs, P, 0), "s_n = n is reproduced");

        var zeros = new long[10];
        Check(BerlekampMassey.Find(zeros, P).Length == 0, "the zero sequence has order 0");
        var constants = new long[10];
        for (int i = 0; i < constants.Length; i++) constants[i] = 7;
        long[] constantCoeffs = BerlekampMassey.Find(constants, P);
        Check(constantCoeffs.Length == 1 && constantCoeffs[0] == 1, "a constant sequence has order 1");

        // A deterministic order-5 LFSR over F_p from splitmix64 coefficients.
        ulong rng = 560001UL;
        var taps = new long[5];
        for (int i = 0; i < 5; i++) taps[i] = 1 + (long)(SplitMix64.Next(ref rng) % (ulong)(P - 2));
        var lfsr = new long[40];
        var seed = new long[5];
        ulong seedRng = 560002UL;
        for (int i = 0; i < 5; i++) seed[i] = (long)(SplitMix64.Next(ref seedRng) % (ulong)P);
        for (int i = 0; i < 5; i++) lfsr[i] = seed[i];
        for (int i = 5; i < lfsr.Length; i++)
        {
            long value = 0;
            for (int j = 0; j < 5; j++) value = (value + taps[j] * lfsr[i - 1 - j]) % P;
            lfsr[i] = value;
        }
        var prefix = new long[10];
        Array.Copy(lfsr, prefix, 10);
        long[] recovered = BerlekampMassey.Find(prefix, P);
        Check(recovered.Length == 5, "the order-5 LFSR is recovered from 2L = 10 terms, got order "
                + recovered.Length);
        for (int i = 0; i < 5; i++)
        {
            Check(recovered[i] == taps[i], "recovered tap " + i + " differs from the generating tap");
        }
        long[] wholeRecovered = BerlekampMassey.Find(lfsr, P);
        Check(wholeRecovered.Length == 5, "more terms do not change the order (still 5)");
        for (int i = 0; i < 5; i++) Check(wholeRecovered[i] == taps[i], "longer input gives the same taps");

        var predicted = BerlekampMassey.Extend(prefix, recovered, P, 20);
        for (int i = 10; i < 20; i++)
        {
            Check(predicted[i] == lfsr[i], "the recovered recurrence predicts term " + i);
        }

        // GF(2): the m-sequence of x^4 + x + 1 has order 4 and period 15.
        const long Two = 2;
        var bits = new long[30];
        var bitSeed = new long[4];
        bitSeed[0] = 1;
        for (int i = 0; i < 4; i++) bits[i] = bitSeed[i];
        for (int i = 4; i < bits.Length; i++) bits[i] = (bits[i - 4] + bits[i - 1]) % Two;
        long[] bitCoeffs = BerlekampMassey.Find(bits, Two);
        Check(bitCoeffs.Length == 4, "the GF(2) sequence has order 4, got " + bitCoeffs.Length);
        Check(bitCoeffs[0] == 1 && bitCoeffs[1] == 0 && bitCoeffs[2] == 0 && bitCoeffs[3] == 1,
                "taps are (1,0,0,1), matching x^4 + x + 1");
        Check(BerlekampMassey.Satisfies(bits, bitCoeffs, Two, 0), "the GF(2) recurrence is reproduced");
        int period = -1;
        for (int candidate = 1; candidate <= 15 && period < 0; candidate++)
        {
            bool works = true;
            for (int i = 0; i + candidate < bits.Length; i++)
            {
                if (bits[i] != bits[i + candidate]) { works = false; break; }
            }
            if (works) period = candidate;
        }
        Check(period == 15, "the m-sequence period is exactly 15, got " + period);

        // Exhaustive minimality over F_97.
        const long Small = 97;
        var smallTaps = new long[] { 1, 96, 5 };
        var smallSeq = new long[24];
        smallSeq[0] = 1;
        smallSeq[1] = 1;
        smallSeq[2] = 1;
        for (int i = 3; i < smallSeq.Length; i++)
        {
            long value = 0;
            for (int j = 0; j < 3; j++) value = (value + smallTaps[j] * smallSeq[i - 1 - j]) % Small;
            smallSeq[i] = value;
        }
        long[] smallRecovered = BerlekampMassey.Find(smallSeq, Small);
        Check(smallRecovered.Length == 3, "the F_97 order-3 sequence is recovered as order 3, got "
                + smallRecovered.Length);
        Check(BerlekampMassey.Satisfies(smallSeq, smallRecovered, Small, 0), "the F_97 recurrence holds");
        Check(!BerlekampMassey.AnyOfOrder(smallSeq, Small, 1), "no order-1 recurrence fits the F_97 sequence");
        Check(!BerlekampMassey.AnyOfOrder(smallSeq, Small, 2), "no order-2 recurrence fits it either");
        Check(BerlekampMassey.AnyOfOrder(smallSeq, Small, 3), "an order-3 recurrence does fit");
        for (int i = 0; i < 3; i++)
        {
            Check(smallRecovered[i] == smallTaps[i], "the exhaustive search agrees with BM at tap " + i);
        }

        // Documented caveat: a two-term prefix cannot see an order-2 recurrence. The sequence
        // 3, 3, 7, ... over F_97 is generated by the taps (60, 7) (60*3 + 7*3 = 201 = 7 mod 97), and
        // its two-term prefix is also consistent with the order-1 recurrence s_n = s_{n-1}, which then
        // predicts 3 instead of 7.
        var caveatSeq = new long[20];
        caveatSeq[0] = 3;
        caveatSeq[1] = 3;
        for (int i = 2; i < caveatSeq.Length; i++)
        {
            caveatSeq[i] = (60 * caveatSeq[i - 1] + 7 * caveatSeq[i - 2]) % Small;
        }
        long[] caveatFull = BerlekampMassey.Find(caveatSeq, Small);
        Check(caveatFull.Length == 2, "the caveat sequence has order 2 over F_97, got " + caveatFull.Length);
        Check(BerlekampMassey.Satisfies(caveatSeq, caveatFull, Small, 0), "the caveat recurrence holds");
        var twoTerms = new long[] { caveatSeq[0], caveatSeq[1] };
        long[] shortRecurrence = BerlekampMassey.Find(twoTerms, Small);
        Check(shortRecurrence.Length == 1, "two equal terms support only an order-1 recurrence, got order "
                + shortRecurrence.Length);
        Check(BerlekampMassey.Satisfies(twoTerms, shortRecurrence, Small, 0),
                "the short recurrence does fit the two terms it was given");
        long[] shortPrediction = BerlekampMassey.Extend(twoTerms, shortRecurrence, Small, 3);
        Check(shortPrediction[2] != caveatSeq[2], "but it mispredicts the third term, as the caveat says");

        // Determinism.
        long[] repeat = BerlekampMassey.Find(fibonacci, P);
        Check(repeat.Length == fibCoeffs.Length && repeat[0] == fibCoeffs[0] && repeat[1] == fibCoeffs[1],
                "repeated runs give the same recurrence");
        long[] repeatLfsr = BerlekampMassey.Find(lfsr, P);
        for (int i = 0; i < 5; i++) Check(repeatLfsr[i] == wholeRecovered[i], "LFSR recovery is stable");

        Console.WriteLine("PASS");
    }

    private static void Check(bool ok, string label)
    {
        if (!ok) throw new Exception("FAILED: " + label);
    }
}

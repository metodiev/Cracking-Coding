/** Task 921 - Implement robot manipulation planner with grasp sampling and scoring.
 *  (Tier: Master, CTCI Beyond - Graphics, Geometry & Robotics)
 *
 * The planner samples antipodal two-contact grasps on a planar polygon boundary, scores them and
 * returns the best reachable, collision-free pick plan for a 2-link arm.
 *   sampling     surface points per edge; a pair qualifies when the outward normals are nearly
 *                antiparallel and the closing segment stays inside the polygon (midpoint interior,
 *                no crossing of a polygon edge);
 *   force closure two independent tests: the wrench test (0 must lie in the interior of the convex
 *                hull of the four unit friction-cone wrenches, solved as a 3x3 barycentric system)
 *                and the classic cone-angle criterion (the segment must lie inside both friction
 *                cones); they must agree;
 *   scoring      force-closure margin (radians of slack) minus grasp-width and approach penalties;
 *   planning     2-link inverse kinematics for a pre-grasp point plus a clearance sweep of the
 *                approach segment against circle obstacles.
 * Simplification: planar polygons, point contacts, circle obstacles, no regrasp sequencing.
 * Verified: the two closure tests agree, frictionless grasps are never closed, the analytic
 * "adjacent faces need mu > 1" threshold holds, closure is monotone in mu, the returned plan is
 * force-closed, kinematically feasible (forward kinematics re-check) and collision-free.
 */
"use strict";
const assert = require("node:assert");

class Prng {
  constructor(seed) { this.state = (seed >>> 0) || 0x9e3779b9; }
  next() {
    let x = this.state;
    x ^= x << 13; x >>>= 0;
    x ^= x >>> 17; x ^= x << 5;
    return (this.state = x >>> 0);
  }
  float() { return this.next() / 4294967296; }
  sym(s) { return (this.float() * 2 - 1) * s; }
}

const sub = (a, b) => ({ x: a.x - b.x, y: a.y - b.y });
const len = (v) => Math.hypot(v.x, v.y);
const unit = (v) => { const n = len(v); return { x: v.x / n, y: v.y / n }; };
const dot = (a, b) => a.x * b.x + a.y * b.y;
const perp = (v) => ({ x: -v.y, y: v.x });
const cross = (a, b) => a.x * b.y - a.y * b.x;
const clamp = (v, lo, hi) => (v < lo ? lo : v > hi ? hi : v);

function polygonArea(polygon) {
  assert.ok(Array.isArray(polygon) && polygon.length >= 3, "a polygon needs at least 3 vertices");
  let twice = 0;
  for (let k = 0; k < polygon.length; k++) {
    const a = polygon[k], b = polygon[(k + 1) % polygon.length];
    assert.ok(Number.isFinite(a.x) && Number.isFinite(a.y), "polygon vertices must be finite");
    twice += a.x * b.y - b.x * a.y;
  }
  assert.ok(Math.abs(twice) > 1e-9, "the polygon is degenerate (zero area)");
  return twice / 2;
}

function pointInPolygon(polygon, p) {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[i], b = polygon[j];
    if ((a.y > p.y) !== (b.y > p.y)
      && p.x < ((b.x - a.x) * (p.y - a.y)) / (b.y - a.y) + a.x) inside = !inside;
  }
  return inside;
}

/** Proper crossing only: touching (including at an endpoint) never counts as crossing. */
function segmentsCross(a, b, c, d) {
  const d1 = cross(sub(b, a), sub(c, a)), d2 = cross(sub(b, a), sub(d, a));
  const d3 = cross(sub(d, c), sub(a, c)), d4 = cross(sub(d, c), sub(b, c));
  const eps = 1e-12;
  if (Math.abs(d1) <= eps || Math.abs(d2) <= eps || Math.abs(d3) <= eps || Math.abs(d4) <= eps) {
    return false;
  }
  return ((d1 > 0) !== (d2 > 0)) && ((d3 > 0) !== (d4 > 0));
}

/** A closing segment may only touch the boundary at its two contacts, never cross it. */
function segmentInsidePolygon(polygon, a, b) {
  if (!pointInPolygon(polygon, { x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 })) return false;
  for (let k = 0; k < polygon.length; k++) {
    const c = polygon[k], d = polygon[(k + 1) % polygon.length];
    if (segmentsCross(a, b, c, d)) return false;
  }
  return true;
}

/** Outward surface samples with unit normals; the polygon may be given clockwise or counter-clockwise. */
function sampleSurface(polygon, perEdge, prng) {
  const orientation = Math.sign(polygonArea(polygon));
  const points = [];
  for (let k = 0; k < polygon.length; k++) {
    const a = polygon[k], b = polygon[(k + 1) % polygon.length];
    const edge = sub(b, a);
    const outward = unit(orientation > 0 ? { x: edge.y, y: -edge.x } : { x: -edge.y, y: edge.x });
    for (let s = 0; s < perEdge; s++) {
      const t = (s + 0.5 + (prng ? prng.sym(0.3 / perEdge) : 0)) / perEdge;
      points.push({ p: { x: a.x + edge.x * t, y: a.y + edge.y * t }, n: outward, edge: k });
    }
  }
  return points;
}

function contact(point, normal) { return { p: point, n: normal }; }

/** Unit wrenches generated by the two extreme rays of the contact friction cone. */
function frictionWrenches(c, mu) {
  const inward = { x: -c.n.x, y: -c.n.y };
  const tangent = perp(inward);
  return [1, -1].map((sign) => {
    const f = unit({ x: inward.x + sign * mu * tangent.x, y: inward.y + sign * mu * tangent.y });
    return [f.x, f.y, c.p.x * f.y - c.p.y * f.x];
  });
}

/** 0 is force-closed iff it is in the interior of the four-wrench convex hull (barycentric solve). */
function forceClosureWrench(contacts, mu) {
  assert.ok(mu >= 0, "the friction coefficient must be non-negative");
  const w = contacts.flatMap((c) => frictionWrenches(c, mu));
  const [w1, w2, w3, w4] = w;
  const A = [[w2[0] - w1[0], w3[0] - w1[0], w4[0] - w1[0]],
    [w2[1] - w1[1], w3[1] - w1[1], w4[1] - w1[1]],
    [w2[2] - w1[2], w3[2] - w1[2], w4[2] - w1[2]]];
  const det = A[0][0] * (A[1][1] * A[2][2] - A[1][2] * A[2][1])
    - A[0][1] * (A[1][0] * A[2][2] - A[1][2] * A[2][0])
    + A[0][2] * (A[1][0] * A[2][1] - A[1][1] * A[2][0]);
  if (Math.abs(det) < 1e-12) return { closed: false, slack: 0 }; // degenerate: not full dimensional
  const rhs = [-w1[0], -w1[1], -w1[2]];
  const solve = (col) => { // Cramer's rule on the 3x3 system
    const M = A.map((row, i) => row.map((v, j) => (j === col ? rhs[i] : v)));
    return (M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1])
      - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
      + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0])) / det;
  };
  const lambda = [solve(0), solve(1), solve(2)];
  lambda.push(1 - lambda[0] - lambda[1] - lambda[2]);
  const slack = Math.min(...lambda);
  return { closed: slack > 1e-9, slack };
}

/** Independent oracle: the classic criterion - the closing segment must lie inside both cones. */
function forceClosureConeAngle(contacts, mu) {
  if (mu <= 0) return { closed: false, slack: 0 };
  const limit = Math.atan(mu);
  let slack = Infinity;
  for (const c of contacts) {
    const other = contacts.find((o) => o !== c);
    const inward = { x: -c.n.x, y: -c.n.y };
    const toward = unit(sub(other.p, c.p));
    const angle = Math.acos(clamp(dot(inward, toward), -1, 1));
    slack = Math.min(slack, limit - angle);
  }
  return { closed: slack > 1e-9, slack };
}

/** Antipodal grasp candidates: near-opposite normals, closing segment inside the object. */
function sampleGrasps(polygon, options = {}) {
  const perEdge = options.perEdge ?? 7;
  assert.ok(Number.isInteger(perEdge) && perEdge > 0, "perEdge must be a positive integer");
  const mu = options.mu ?? 0.6;
  const maxWidth = options.maxWidth ?? 1.2;
  const samples = sampleSurface(polygon, perEdge, options.prng);
  const grasps = [];
  for (let i = 0; i < samples.length; i++) {
    for (let j = i + 1; j < samples.length; j++) {
      const a = samples[i], b = samples[j];
      if (a.edge === b.edge) continue;
      if (dot(a.n, b.n) > -0.9) continue; // not antipodal enough
      const width = len(sub(b.p, a.p));
      if (width > maxWidth) continue;
      if (!segmentInsidePolygon(polygon, a.p, b.p)) continue;
      const contacts = [contact(a.p, a.n), contact(b.p, b.n)];
      const wrench = forceClosureWrench(contacts, mu);
      grasps.push({ contacts, width, center: { x: (a.p.x + b.p.x) / 2, y: (a.p.y + b.p.y) / 2 },
        axis: unit(sub(b.p, a.p)), closed: wrench.closed, closureSlack: wrench.slack, mu });
    }
  }
  return grasps;
}

/* ------------------------------------------------------------------ 2-link arm planner */

function forwardKinematics(joints, links) {
  const [q1, q2] = joints;
  return { x: links[0] * Math.cos(q1) + links[1] * Math.cos(q1 + q2),
    y: links[0] * Math.sin(q1) + links[1] * Math.sin(q1 + q2) };
}

/** Elbow-up inverse kinematics; null when the target is outside the reachable annulus. */
function inverseKinematics(target, links) {
  const [l1, l2] = links;
  const r = Math.hypot(target.x, target.y);
  if (r > l1 + l2 || r < Math.abs(l1 - l2)) return null;
  const cosQ2 = clamp((r * r - l1 * l1 - l2 * l2) / (2 * l1 * l2), -1, 1);
  const q2 = -Math.acos(cosQ2);
  const q1 = Math.atan2(target.y, target.x) - Math.atan2(l2 * Math.sin(q2), l1 + l2 * Math.cos(q2));
  return [q1, q2];
}

/** Smallest clearance between a segment and the circular obstacles (negative means collision). */
function pathClearance(a, b, obstacles, radius) {
  let best = Infinity;
  const d = sub(b, a);
  const lengthSquared = dot(d, d) || 1e-12;
  for (const o of obstacles) {
    const t = clamp(dot(sub(o, a), d) / lengthSquared, 0, 1);
    const closest = { x: a.x + d.x * t, y: a.y + d.y * t };
    best = Math.min(best, len(sub(o, closest)) - o.r - radius);
  }
  return best;
}

/**
 * Pick plan: for every force-closed candidate try both approach directions, keep the plans whose
 * pre-grasp point is reachable and whose approach segment is clear, then score and rank them.
 */
function planGrasp(polygon, problem = {}) {
  const links = problem.links ?? [0.75, 0.55];
  const obstacles = problem.obstacles ?? [];
  const standoff = problem.standoff ?? 0.25;
  const jawRadius = problem.jawRadius ?? 0.03;
  const mu = problem.mu ?? 0.6;
  const grasps = sampleGrasps(polygon, { ...problem, mu });
  const plans = [];
  for (const grasp of grasps) {
    if (!grasp.closed) continue;
    for (const side of [1, -1]) {
      const approach = { x: -grasp.axis.y * side, y: grasp.axis.x * side };
      const preGrasp = { x: grasp.center.x + approach.x * standoff, y: grasp.center.y + approach.y * standoff };
      const joints = inverseKinematics(preGrasp, links);
      if (!joints) continue;
      const clearance = pathClearance(preGrasp, grasp.center, obstacles, jawRadius);
      if (clearance <= 0) continue;
      const score = grasp.closureSlack - 0.5 * (grasp.width / (problem.maxWidth ?? 1.2))
        + 0.5 * clamp(clearance / 0.2, 0, 1);
      plans.push({ grasp, approach, preGrasp, joints, clearance, score });
    }
  }
  plans.sort((a, b) => b.score - a.score || a.grasp.width - b.grasp.width);
  return { best: plans[0] ?? null, plans,
    reason: plans.length === 0 ? "no force-closed reachable collision-free grasp" : null,
    sampled: grasps.length };
}

/* ------------------------------------------------------------------ checks */

const RECTANGLE = [{ x: -0.4, y: -0.25 }, { x: 0.4, y: -0.25 }, { x: 0.4, y: 0.25 }, { x: -0.4, y: 0.25 }];

function main() {
  const problem = { mu: 0.6, maxWidth: 1.2, links: [0.75, 0.55], standoff: 0.25, jawRadius: 0.03,
    obstacles: [{ x: 1.1, y: 0.9, r: 0.3 }] };

  // 1. Sampling produces antipodal, in-object, width-limited grasps and all of them use two contacts.
  const grasps = sampleGrasps(RECTANGLE, problem);
  assert.ok(grasps.length >= 6, `expected several grasp candidates, got ${grasps.length}`);
  for (const g of grasps) {
    assert.strictEqual(g.contacts.length, 2);
    assert.ok(dot(g.contacts[0].n, g.contacts[1].n) <= -0.9, "candidate is not antipodal");
    assert.ok(g.width <= problem.maxWidth + 1e-12, "candidate is wider than the jaws");
    assert.ok(segmentInsidePolygon(RECTANGLE, g.contacts[0].p, g.contacts[1].p), "segment leaves body");
  }

  // 2. Independent oracle: wrench test and the cone-angle criterion agree away from the boundary.
  let compared = 0;
  for (const mu of [0.3, 0.6, 1.0, 1.5]) {
    for (const g of sampleGrasps(RECTANGLE, { ...problem, mu })) {
      const wrench = forceClosureWrench(g.contacts, mu);
      const cone = forceClosureConeAngle(g.contacts, mu);
      if (Math.abs(cone.slack) < 1e-6 || Math.abs(wrench.slack) < 1e-6) continue; // marginal
      assert.strictEqual(wrench.closed, cone.closed,
        `tests disagree at mu=${mu} (wrench ${wrench.closed}, cone ${cone.closed})`);
      compared++;
    }
  }
  assert.ok(compared >= 10, `the oracle comparison covered only ${compared} grasps`);

  // 3. Analytic physics: frictionless grasps never close; adjacent faces need mu > 1.
  const topFace = contact({ x: 0, y: 0.25 }, { x: 0, y: 1 });
  const bottomFace = contact({ x: 0, y: -0.25 }, { x: 0, y: -1 });
  assert.strictEqual(forceClosureWrench([topFace, bottomFace], 0).closed, false,
    "a frictionless two-point grasp cannot be force-closed");
  assert.strictEqual(forceClosureWrench([topFace, bottomFace], 0.5).closed, true,
    "opposite parallel faces must close with friction");
  const rightFace = contact({ x: 0.4, y: -0.2 }, { x: 1, y: 0 });
  const nearCorner = contact({ x: -0.2, y: 0.25 }, { x: 0, y: 1 });
  assert.strictEqual(forceClosureWrench([rightFace, nearCorner], 0.5).closed, false,
    "adjacent faces must not close for mu = 0.5");
  assert.strictEqual(forceClosureWrench([rightFace, nearCorner], 2).closed, true,
    "adjacent faces must close for mu = 2");
  assert.strictEqual(forceClosureConeAngle([rightFace, nearCorner], 2).closed, true,
    "the cone criterion must agree that mu = 2 closes this grasp");

  // 4. Closure is monotone in mu: anything closed at mu stays closed at larger mu.
  for (const g of grasps) {
    if (!g.closed) continue;
    for (const mu of [1, 2]) {
      assert.ok(forceClosureWrench(g.contacts, mu).closed, "closure must survive a larger mu");
    }
  }

  // 5. The returned plan is closed, reachable (forward kinematics re-check) and collision-free.
  const plan = planGrasp(RECTANGLE, problem);
  assert.ok(plan.best, `planner failed: ${plan.reason}`);
  const best = plan.best;
  assert.ok(forceClosureWrench(best.grasp.contacts, problem.mu).closed, "best plan is not closed");
  const reached = forwardKinematics(best.joints, problem.links);
  assert.ok(Math.hypot(reached.x - best.preGrasp.x, reached.y - best.preGrasp.y) < 1e-9,
    "the joint solution does not reach the pre-grasp point");
  assert.ok(best.clearance > 0, "the chosen approach collides with an obstacle");
  assert.ok(pathClearance(best.preGrasp, best.grasp.center, problem.obstacles, problem.jawRadius) > 0);

  // 6. Ranking: plans are sorted by descending score and best is the maximum.
  assert.ok(plan.plans.length >= 1);
  for (let k = 1; k < plan.plans.length; k++) {
    assert.ok(plan.plans[k - 1].score >= plan.plans[k].score - 1e-12, "plans are not ranked");
  }
  assert.strictEqual(best.score, Math.max(...plan.plans.map((p) => p.score)));

  // 7. Boundary cases: unreachable jaws and a blocked approach yield an explicit failure.
  const tooNarrow = planGrasp(RECTANGLE, { ...problem, maxWidth: 0.2, mu: 0.6 });
  assert.strictEqual(tooNarrow.best, null);
  assert.match(tooNarrow.reason, /no force-closed reachable/);
  const blocked = planGrasp(RECTANGLE, { ...problem, obstacles: [{ x: 0, y: 0, r: 0.9 }] });
  assert.strictEqual(blocked.best, null, "an obstacle enclosing the object must block every plan");
  const square = planGrasp([{ x: -0.2, y: -0.2 }, { x: 0.2, y: -0.2 }, { x: 0.2, y: 0.2 }, { x: -0.2, y: 0.2 }],
    { ...problem, maxWidth: 0.5 });
  assert.ok(square.best, "a small square must be graspable within narrow jaws");

  // 8. Determinism: identical seeds give an identical plan, a different seed still gives a valid one.
  const seeded = planGrasp(RECTANGLE, { ...problem, prng: new Prng(21) });
  const again = planGrasp(RECTANGLE, { ...problem, prng: new Prng(21) });
  assert.deepStrictEqual(seeded.best, again.best);
  const other = planGrasp(RECTANGLE, { ...problem, prng: new Prng(22) });
  assert.ok(other.best && forceClosureWrench(other.best.grasp.contacts, problem.mu).closed,
    "a different seed must still produce a valid plan");
  assert.ok(other.best.clearance > 0);

  // 9. Invalid input is rejected.
  assert.throws(() => polygonArea([{ x: 0, y: 0 }, { x: 1, y: 1 }]), /at least 3 vertices/);
  assert.throws(() => polygonArea([{ x: 0, y: 0 }, { x: 1, y: 1 }, { x: 2, y: 2 }]), /degenerate/);
  assert.throws(() => forceClosureWrench([topFace, bottomFace], -1), /non-negative/);
  assert.throws(() => sampleGrasps(RECTANGLE, { perEdge: 0 }), /positive integer/);

  console.log(`grasp: ${grasps.length} candidates, ${plan.plans.length} feasible plans, best score ` +
    `${best.score.toFixed(4)}, closure slack ${best.grasp.closureSlack.toFixed(4)}, ` +
    `clearance ${best.clearance.toFixed(4)}`);
  console.log("PASS");
}

if (require.main === module) main();
module.exports = { Prng, polygonArea, pointInPolygon, segmentInsidePolygon, sampleSurface,
  frictionWrenches, forceClosureWrench, forceClosureConeAngle, sampleGrasps, forwardKinematics,
  inverseKinematics, pathClearance, planGrasp, contact };

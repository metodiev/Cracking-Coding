/** Task 767 - Implement online re-ranking with features and click simulation (learning-to-rank). (Tier: Expert, CTCI Beyond — Machine Learning & AI)
 *
 * A learning-to-rank loop with the three pieces that make it honest: a feature model, a *position
 * biased* click simulator, and counters that are corrected for that bias before anything is learned.
 * Documents carry four features (query match, quality prior, freshness, length normalisation) and an
 * unseen graded relevance; the ranker is linear (`score = w · features`) and starts from a baseline
 * that only trusts the match feature. Clicks are generated by the position-based model
 * `P(click | doc at rank r) = relevance * 1/log2(r + 2)`, which is exactly the bias the estimator has
 * to undo: the naive CTR per position *is* biased by the propensity, while the inverse-propensity
 * (IPS) weighted estimate converges to the true relevance. Learning is the classic pairwise update
 * from click logs: for a clicked document ranked above a skipped one, nudge the weights along
 * `features(clicked) - features(skipped)` until the margin is satisfied. Evaluation is NDCG@10
 * against the hidden grades, compared with an offline grid search over candidate weight vectors.
 *
 * What is simplified: 12 queries and 20 candidates with synthetic features and synthetically sampled
 * clicks (no real user behaviour, no exploration policy, no counterfactual evaluation beyond IPS on
 * the same simulator), and a linear model with pairwise updates rather than the full LambdaMART.
 * What is verified: the click model's empirical frequency matches `relevance * propensity`; the naive
 * per-position CTR is biased while the IPS estimate stays within tolerance of the truth; the pairwise
 * update strictly increases the margin of the pair it was trained on and does nothing when there is
 * no click or no skip; the online loop improves NDCG@10 and lands close to an offline grid optimum;
 * determinism of the whole trajectory; and degenerate inputs.
 */
"use strict";

const { deepStrictEqual, strictEqual, ok, throws } = require("node:assert");

/** Deterministic xorshift32 with a uniform float in [0, 1). */
function makeRng(seed) {
  let state = seed >>> 0 || 0x767767;
  const next = (bound) => {
    state ^= state << 13; state >>>= 0;
    state ^= state >>> 17;
    state ^= state << 5; state >>>= 0;
    return bound === undefined ? state : state % bound;
  };
  next.float = () => next(1 << 24) / (1 << 24);
  return next;
}

/** Position-based propensity: how likely a user inspects position `rank` (0-based). */
const propensity = (rank) => 1 / Math.log2(rank + 2);

const dot = (weights, features) => weights.reduce((total, weight, index) => total + weight * features[index], 0);
const clamp01 = (value) => Math.max(0, Math.min(1, value));
const gradesToRelevance = (grade) => clamp01(grade / 4);

/** Synthetic corpus: features in [0, 1], a hidden grade, and a hidden per-document quality. */
function buildCorpus(queries, candidates, seed) {
  const rng = makeRng(seed);
  return Array.from({ length: queries }, (_, queryId) => {
    const documents = Array.from({ length: candidates }, (_, docId) => {
      const match = rng.float();
      const quality = rng.float();
      const freshness = rng.float();
      const length = 1 + rng(400);
      const grade = Math.round(4 * clamp01(0.65 * match + 0.25 * quality + 0.1 * freshness));
      return {
        docId, grade, match, quality, freshness,
        features: [match, quality, freshness, 1 / Math.log2(2 + length)],
      };
    });
    return { queryId, documents };
  });
}

/** Linear ranker with a pairwise perceptron update. */
class Ranker {
  constructor(featureCount, { eta = 0.05, margin = 0.1 } = {}) {
    if (!Number.isInteger(featureCount) || featureCount < 1) throw new RangeError("featureCount must be positive");
    if (eta <= 0) throw new RangeError("eta must be positive");
    if (margin < 0) throw new RangeError("margin must be non-negative");
    this.weights = new Array(featureCount).fill(0);
    this.weights[0] = 1;                       // the baseline trusts only the first feature
    this.eta = eta;
    this.margin = margin;
    this.updates = 0;
  }

  score(features) { return dot(this.weights, features); }

  rank(documents) {
    return documents.map((document) => ({ document, score: this.score(document.features) }))
      .sort((left, right) => right.score - left.score || left.document.docId - right.document.docId)
      .map((entry) => entry.document);
  }

  /** One pairwise step: pull the clicked document above the skipped one. */
  update(clicked, skipped) {
    if (clicked === undefined || skipped === undefined || clicked === skipped) return false;
    const delta = clicked.features.map((feature, index) => feature - skipped.features[index]);
    if (delta.every((value) => value === 0)) return false;            // no signal to learn from
    if (this.score(clicked.features) > this.score(skipped.features) + this.margin) return false;
    this.weights = this.weights.map((weight, index) => weight + this.eta * delta[index]);
    this.updates++;
    return true;
  }
}

/** Position-based click model: examination depends on the rank, the click on the relevance. */
function simulateClicks(ranking, rng) {
  return ranking.map((document, rank) => {
    const examined = rng.float() < propensity(rank);
    const clicked = examined && rng.float() < gradesToRelevance(document.grade);
    return { document, rank, examined, clicked };
  });
}

const dcg = (gains) => gains.reduce((total, gain, index) => total + (2 ** gain - 1) / Math.log2(index + 2), 0);

const ndcgAt = (ranking, k) => {
  const grades = ranking.map((document) => document.grade);
  const best = dcg([...grades].sort((a, b) => b - a).slice(0, k));
  return best === 0 ? 0 : dcg(grades.slice(0, k)) / best;
};

/**
 * Position bias analysis: naive CTR per position versus the inverse-propensity weighted estimate of
 * the true relevance, both read off the same simulator log.
 */
function biasReport(log, positions) {
  const naive = positions.map((rank) => {
    const impressions = log.filter((entry) => entry.rank === rank);
    return impressions.length === 0 ? 0 : impressions.filter((entry) => entry.clicked).length / impressions.length;
  });
  const ips = positions.map((rank) => {
    const impressions = log.filter((entry) => entry.rank === rank);
    if (impressions.length === 0) return 0;
    const total = impressions.reduce((sum, entry) => sum + entry.clicked / propensity(rank), 0);
    return total / impressions.length;
  });
  return { naive, ips };
}

/** Offline oracle: the best mean NDCG@10 over a grid of candidate weight vectors. */
function bestGridWeights(corpus, k = 10) {
  let best = { weights: null, ndcg: -1 };
  for (let first = 0; first <= 10; first++) {
    for (let second = 0; second <= 10; second++) {
      for (const third of [0, 5, 10]) {
        const weights = [first / 10, second / 10, third / 10, 1];
        const ranker = new Ranker(4);
        ranker.weights = weights;
        const value = corpus.reduce((total, query) => total + ndcgAt(ranker.rank(query.documents), k), 0) / corpus.length;
        if (value > best.ndcg) best = { weights, ndcg: value };
      }
    }
  }
  return best;
}

/** One online session: show every query many times, learn from the clicked/skipped pairs. */
function train(corpus, ranker, rounds, seed, k = 10) {
  const rng = makeRng(seed);
  const trajectory = [];
  for (let round = 0; round < rounds; round++) {
    for (const query of corpus) {
      const ranking = ranker.rank(query.documents);
      const impressions = simulateClicks(ranking, rng);
      const clicked = impressions.filter((entry) => entry.clicked);
      const skipped = impressions.filter((entry) => !entry.clicked);
      for (const positive of clicked) {
        for (const negative of skipped) {
          if (positive.rank < negative.rank) ranker.update(positive.document, negative.document);
        }
      }
    }
    trajectory.push(corpus.reduce((total, query) => total + ndcgAt(ranker.rank(query.documents), k), 0) / corpus.length);
  }
  return trajectory;
}

module.exports = {
  makeRng, propensity, dot, buildCorpus, Ranker, simulateClicks, ndcgAt, dcg,
  biasReport, bestGridWeights, train,
};

if (require.main === module) {
  const CORPUS = buildCorpus(12, 20, 0x767767);
  const K = 10;

  // 1. the click model matches its own closed form: a click at rank r happens with relevance * propensity
  const target = CORPUS[1].documents[3];
  const relevance = gradesToRelevance(target.grade);
  const log = [];
  for (let trial = 0; trial < 3000; trial++) {
    for (const rank of [0, 1, 4]) {
      const ranking = Array.from({ length: rank + 1 }, () => CORPUS[0].documents[0]);
      ranking[rank] = target;
      const entry = simulateClicks(ranking, makeRng(trial * 31 + rank + 1))[rank];
      log.push({ rank, clicked: entry.clicked, document: target });
    }
  }
  const report = biasReport(log, [0, 1, 4]);
  [0, 1, 4].forEach((rank, index) => {
    if (rank > 0) ok(propensity(rank) < propensity(rank - 1), "propensity must fall with rank");
    ok(Math.abs(report.naive[index] - relevance * propensity(rank)) < 0.06,
      `the naive CTR at rank ${rank} tracks relevance * propensity`);
    ok(Math.abs(report.ips[index] - relevance) < 0.06, `and the IPS estimate recovers the relevance itself (rank ${rank})`);
  });
  // 2. over a whole corpus the naive CTR per position is biased, the IPS estimate is not
  const deepLog = CORPUS.flatMap((query) => {
    const ranking = query.documents.slice(0, 10);
    return Array.from({ length: 60 }, (_, trial) => simulateClicks(ranking, makeRng(query.queryId * 1000 + trial)))
      .flat().map((entry) => ({ rank: entry.rank, clicked: entry.clicked }));
  });
  const positions = [0, 1, 4, 9];
  const deep = biasReport(deepLog, positions);
  const relevanceAt = (rank) => CORPUS.reduce((total, query) => total + gradesToRelevance(query.documents[rank].grade), 0) / CORPUS.length;
  ok(deep.naive[0] > deep.naive[3], `the naive CTR decays with position (${deep.naive[0].toFixed(3)} -> ${deep.naive[3].toFixed(3)})`);
  positions.forEach((rank, index) => {
    ok(Math.abs(deep.naive[index] - relevanceAt(rank) * propensity(rank)) < 0.08, `naive CTR at rank ${rank} follows the propensity`);
    ok(Math.abs(deep.ips[index] - relevanceAt(rank)) < 0.1, `IPS at rank ${rank} stays near the truth`);
  });
  ok(Math.abs(deep.ips[3] - relevanceAt(9)) < Math.abs(deep.naive[3] - relevanceAt(9)) / 2,
    "IPS removes much more of the position bias than the raw CTR");
  // 3. the pairwise update strictly increases the margin of the pair it trained on
  const ranker = new Ranker(4, { eta: 0.05, margin: 0.1 });
  const pair = CORPUS[0].documents.slice(0, 2);
  const before = ranker.score(pair[0].features) - ranker.score(pair[1].features);
  const changed = ranker.update(pair[0], pair[1]);
  const after = ranker.score(pair[0].features) - ranker.score(pair[1].features);
  ok(changed && after > before, `the margin must grow (${before.toFixed(3)} -> ${after.toFixed(3)})`);
  // 4. no click and no skip mean no update at all
  const idle = new Ranker(4);
  deepStrictEqual(idle.weights, [1, 0, 0, 0]);
  strictEqual(idle.update(undefined, pair[1]), false, "no clicked document, no update");
  strictEqual(idle.update(pair[0], undefined), false, "no skipped document, no update");
  deepStrictEqual(idle.weights, [1, 0, 0, 0], "the weights are untouched");
  strictEqual(new Ranker(4).update(pair[0], pair[0]), false, "a pair of the same document is not a training signal");
  // 5. a click-count ranking is a valid but biased baseline
  const counts = new Map();
  CORPUS.forEach((query) => {
    const ranking = query.documents.slice(0, 10);
    for (let trial = 0; trial < 200; trial++) {
      for (const entry of simulateClicks(ranking, makeRng(query.queryId * 777 + trial))) {
        if (!entry.clicked) continue;
        const key = `${query.queryId}:${entry.document.docId}`;
        counts.set(key, (counts.get(key) ?? 0) + 1);
      }
    }
  });
  const naiveClickNdcg = CORPUS.reduce((total, query) => {
    const ranked = [...query.documents].sort((a, b) =>
      (counts.get(`${query.queryId}:${b.docId}`) ?? 0) - (counts.get(`${query.queryId}:${a.docId}`) ?? 0) || a.docId - b.docId);
    return total + ndcgAt(ranked, K);
  }, 0) / CORPUS.length;
  ok(naiveClickNdcg >= 0 && naiveClickNdcg <= 1, `a raw click-count ranking is a valid baseline (${naiveClickNdcg.toFixed(3)})`);
  // 6. the online loop improves NDCG and lands near the offline grid optimum
  const baselineNdcg = CORPUS.reduce((total, query) => total + ndcgAt(new Ranker(4).rank(query.documents), K), 0) / CORPUS.length;
  const online = new Ranker(4, { eta: 0.05, margin: 0.1 });
  const trajectory = train(CORPUS, online, 8, 4242, K);
  const learned = CORPUS.reduce((total, query) => total + ndcgAt(online.rank(query.documents), K), 0) / CORPUS.length;
  const oracle = bestGridWeights(CORPUS, K);
  ok(online.updates > 0, `the session produced training updates (${online.updates})`);
  ok(learned > baselineNdcg, `learning improves NDCG@10 (${baselineNdcg.toFixed(3)} -> ${learned.toFixed(3)})`);
  ok(learned >= oracle.ndcg - 0.15, `the online model stays close to the grid optimum (${learned.toFixed(3)} vs ${oracle.ndcg.toFixed(3)})`);
  ok(trajectory.every((value) => value >= 0 && value <= 1), "every NDCG in the trajectory is a fraction");
  ok(trajectory.at(-1) >= trajectory[0], `the trajectory does not fall back (${trajectory[0].toFixed(3)} -> ${trajectory.at(-1).toFixed(3)})`);
  ok(online.weights[0] > 0 && online.weights[1] > 0, `the update redistributed weight (${online.weights.map((w) => w.toFixed(2)).join(",")})`);
  // 7. determinism: the same seed replays the same weights and the same trajectory
  const replayA = new Ranker(4, { eta: 0.05, margin: 0.1 });
  const replayB = new Ranker(4, { eta: 0.05, margin: 0.1 });
  deepStrictEqual(train(CORPUS, replayA, 3, 7, K), train(CORPUS, replayB, 3, 7, K), "the trajectory replays exactly");
  deepStrictEqual(replayA.weights, replayB.weights, "and so do the weights");
  // 8. degenerate inputs
  const single = buildCorpus(1, 1, 5);
  strictEqual(ndcgAt(single[0].documents, K), 1, "a single-document query is trivially perfect");
  strictEqual(ndcgAt([], K), 0, "an empty ranking has no gain");
  strictEqual(ndcgAt(CORPUS[0].documents, 0), 0, "k = 0 truncates everything");
  const noClickLog = CORPUS[0].documents.slice(0, 5).map((document, rank) => ({ document, rank, examined: false, clicked: false }));
  deepStrictEqual(biasReport(noClickLog, [0]).naive, [0], "a log without clicks has a zero CTR");
  throws(() => new Ranker(0), RangeError);
  throws(() => new Ranker(4, { eta: 0 }), RangeError);
  throws(() => new Ranker(4, { margin: -1 }), RangeError);

  console.log(
    `queries=${CORPUS.length} baseline=${baselineNdcg.toFixed(3)} learned=${learned.toFixed(3)} grid=${oracle.ndcg.toFixed(3)} ` +
    `updates=${online.updates} clickCountNdcg=${naiveClickNdcg.toFixed(3)} ` +
    `ipsError=${Math.max(...positions.map((rank, i) => Math.abs(deep.ips[i] - relevanceAt(rank)))).toFixed(3)}`);
  console.log("PASS");
}

/**
 * Task 675 - Implement instruction scheduling heuristics for pipelined CPU model.
 * (Tier: Expert, CTCI Beyond — Compilers, Languages & Solvers)
 *
 * A single-issue in-order pipeline: one instruction issues per cycle, an instruction with latency L
 * makes its result available L cycles after it issues, and dependences are the edges of a DAG. That is
 * exactly the model where list scheduling is the classic heuristic:
 *
 *   ready(t)   - instructions whose dependences have all completed by cycle t;
 *   priority   - "critical-path" (height = longest latency path to a sink), "id" (declaration order) or
 *                "seeded" (a deterministic permutation, as a control);
 *   issue      - greedily take the highest-priority ready instruction that is not yet issued and put it
 *                in the earliest cycle at or after its earliest start that is still free.
 *
 * `lowerBound` is the longest latency path (no schedule can be shorter on this DAG) and `maxOfOrders`
 * is generated by a brute-force sweep over *all* topological orders (n! filtered to topological ones,
 * each scheduled as early as possible), which yields both an independent optimum and a worst case for
 * the heuristic. The schedule itself is validated by `scheduleProblems`, which re-checks every edge
 * (issue[s] >= issue[p] + latency[p]) and that no two instructions share a cycle.
 *
 * Verified: the hand-computed DAG schedule; every heuristic's plan passes scheduleProblems on 12 random
 * DAGs; lowerBound <= list scheduling <= brute-force worst order, and the heuristic is never better than
 * the brute-force optimum; the critical-path heuristic beats declaration order on a DAG built to punish
 * the latter (a long latency chain next to independent work); a dependency chain has makespan equal to
 * the sum of latencies; independent instructions cost one cycle each; empty and single-instruction DAGs;
 * and every run is reproducible.
 */
"use strict";

const assert = require("node:assert");

const MASK64 = (1n << 64n) - 1n;
const DEFAULT_SEED = 0x5eed675n;

class SplitMix64 {
  constructor(seed) {
    this.state = BigInt(seed) & MASK64;
  }
  next() {
    this.state = (this.state + 0x9e3779b97f4a7c15n) & MASK64;
    let z = this.state;
    z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & MASK64;
    z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & MASK64;
    return z ^ (z >> 31n);
  }
  nextInt(n) {
    return Number(this.next() % BigInt(n));
  }
}

// --------------------------------------------------------------------------------------- DAG
const instr = (id, latency, deps = []) => ({ id, latency, deps });
const successors = (dag) => {
  const out = new Map(dag.map((i) => [i.id, []]));
  for (const i of dag) for (const d of i.deps) out.get(d).push(i.id);
  return out;
};
const heightOf = (dag) => {
  const byId = new Map(dag.map((i) => [i.id, i]));
  const memo = new Map();
  const height = (id) => {
    if (memo.has(id)) return memo.get(id);
    const self = byId.get(id);
    const value = self.latency + Math.max(0, ...self.deps.map((d) => height(d)));
    memo.set(id, value);
    return value;
  };
  for (const i of dag) height(i.id);
  return memo;
};
const lowerBound = (dag) => (dag.length === 0 ? 0 : Math.max(...heightOf(dag).values()));

/** Earliest completion cycle implied by the dependences alone. */
function earliestStart(dag) {
  const byId = new Map(dag.map((i) => [i.id, i]));
  const start = new Map();
  const compute = (id) => {
    if (start.has(id)) return start.get(id);
    const self = byId.get(id);
    const value = Math.max(0, ...self.deps.map((d) => compute(d) + byId.get(d).latency));
    start.set(id, value);
    return value;
  };
  for (const i of dag) compute(i.id);
  return start;
}

/**
 * List scheduling. Instructions are ranked by the chosen priority; the scheduler walks cycles in
 * order, and at each cycle issues the highest-ranked instruction whose dependences have all completed
 * (single issue, so an idle cycle simply passes). `seeded` shuffles the ranking with a deterministic
 * PRNG as a control.
 */
function listSchedule(dag, priority = "critical-path", rng = null) {
  const byId = new Map(dag.map((i) => [i.id, i]));
  const heights = heightOf(dag);
  const rank = new Map();
  if (priority === "seeded") {
    const shuffled = [...dag];
    for (let i = shuffled.length - 1; i > 0; i--) {
      const j = rng.nextInt(i + 1);
      [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    shuffled.forEach((i, index) => rank.set(i.id, index));
  }
  const ranked = [...dag].sort((a, b) => {
    const key = (i) => (priority === "id" ? i.id : priority === "seeded" ? rank.get(i.id) : -heights.get(i.id));
    return key(a) - key(b) || a.id - b.id;
  });
  const issue = new Map();
  let remaining = dag.length;
  let cycle = 0;
  const horizon = dag.reduce((acc, i) => acc + i.latency, 0) + dag.length + 1;
  while (remaining > 0) {
    assert.ok(cycle <= horizon, "the scheduler must not run past the sum of all latencies");
    for (const candidate of ranked) {
      if (issue.has(candidate.id)) continue;
      if (!candidate.deps.every((d) => issue.has(d))) continue;
      const readyAt = Math.max(0, ...candidate.deps.map((d) => issue.get(d) + byId.get(d).latency));
      if (readyAt > cycle) continue;
      issue.set(candidate.id, cycle);
      remaining -= 1;
      break;
    }
    cycle += 1;
  }
  const makespan = dag.length === 0 ? 0 : Math.max(...dag.map((i) => issue.get(i.id) + i.latency));
  return { issue, makespan, order: ranked.map((i) => i.id) };
}

/** Schedule a given order greedily (earliest free cycle) - the primitive used by the brute force. */
function scheduleInOrder(dag, order) {
  const byId = new Map(dag.map((i) => [i.id, i]));
  const issue = new Map();
  const busy = new Set();
  for (const id of order) {
    const i = byId.get(id);
    let cycle = Math.max(0, ...i.deps.map((d) => issue.get(d) + byId.get(d).latency));
    while (busy.has(cycle)) cycle += 1;
    issue.set(id, cycle);
    busy.add(cycle);
  }
  return { issue, makespan: dag.length === 0 ? 0 : Math.max(...dag.map((i) => issue.get(i.id) + i.latency)) };
}

/** Every topological order of the DAG (small DAGs only), each scheduled greedily. */
function bruteForceOrders(dag, limit = 20000) {
  const succ = successors(dag);
  const indeg = new Map(dag.map((i) => [i.id, i.deps.length]));
  const results = [];
  let visited = 0;
  const walkOrder = (prefix, degrees) => {
    if (prefix.length === dag.length) {
      results.push(scheduleInOrder(dag, prefix));
      return;
    }
    for (const i of dag) {
      if (degrees.get(i.id) !== 0 || prefix.includes(i.id)) continue;
      visited += 1;
      if (visited > limit) return;
      const next = new Map(degrees);
      for (const s of succ.get(i.id)) next.set(s, next.get(s) - 1);
      walkOrder([...prefix, i.id], next);
      if (visited > limit) return;
    }
  };
  walkOrder([], new Map(indeg));
  const makespans = results.map((r) => r.makespan);
  return { orders: results.length, best: makespanS(makespans, Math.min), worst: makespanS(makespans, Math.max), visited };
}
const makespanS = (values, fn) => (values.length === 0 ? 0 : fn(...values));

/** Every edge respected, and exactly one instruction per cycle. */
function scheduleProblems(dag, schedule) {
  const byId = new Map(dag.map((i) => [i.id, i]));
  const bad = [];
  const cycles = new Set();
  for (const i of dag) {
    const at = schedule.issue.get(i.id);
    if (at === undefined) bad.push(`${i.id} never issued`);
    else {
      if (cycles.has(at)) bad.push(`two instructions in cycle ${at}`);
      cycles.add(at);
    }
    for (const d of i.deps) {
      const dep = byId.get(d);
      if (at < schedule.issue.get(d) + dep.latency) bad.push(`${i.id} starts before ${d} produced its result`);
    }
  }
  return bad;
}

// ----------------------------------------------------------------------------------- test DAGs
/** Three single-cycle units, plus a long-latency chain whose instructions get the *highest* ids. */
const chainPlusWork = () => [
  instr(0, 1), instr(1, 1), instr(2, 1), instr(3, 3), instr(4, 4, [3]), instr(5, 1, [4]),
];

/** Two independent chains of different lengths. */
const twoChains = () => [
  instr(0, 2), instr(1, 3, [0]), instr(2, 1, [1]),
  instr(3, 1), instr(4, 4, [3]),
];

/** A diamond: 0 feeds 1 and 2, both feed 3. */
const diamond = () => [instr(0, 2), instr(1, 3, [0]), instr(2, 1, [0]), instr(3, 2, [1, 2])];

function randomDag(rng, n) {
  const dag = [];
  for (let i = 0; i < n; i++) {
    const deps = [];
    for (let j = 0; j < i; j++) if (rng.nextInt(3) === 0) deps.push(j);
    dag.push(instr(i, 1 + rng.nextInt(4), deps));
  }
  return dag;
}

function main() {
  // (1) Hand-computed schedule for the chain-plus-work DAG.
  const dag = chainPlusWork();
  const cp = listSchedule(dag, "critical-path");
  assert.deepStrictEqual([0, 1, 2, 3, 4, 5].map((id) => cp.issue.get(id)), [1, 2, 4, 0, 3, 7],
    "the chain issues first (3 at cycle 0, 4 at 3, 5 at 7) and the independent units fill cycles 1, 2, 4");
  assert.deepStrictEqual([cp.makespan, lowerBound(dag)], [8, 8],
    "the longest latency path is 3 + 4 + 1 = 8 and the heuristic reaches it");
  assert.deepStrictEqual(scheduleProblems(dag, cp), [], "the schedule respects every edge and single issue");
  assert.deepStrictEqual([earliestStart(dag).get(5), cp.order], [7, [5, 4, 3, 0, 1, 2]],
    "5 cannot start before cycle 7, and the ranking puts the chain's tail blocks first");

  // (2) Every heuristic produces a legal plan on every DAG.
  const dags = [dag, twoChains(), diamond()];
  const rng = new SplitMix64(DEFAULT_SEED);
  for (let i = 0; i < 12; i++) dags.push(randomDag(rng, 4 + rng.nextInt(4)));
  let placed = 0;
  for (const graph of dags) {
    for (const priority of ["critical-path", "id", "seeded"]) {
      const plan = listSchedule(graph, priority, rng);
      assert.deepStrictEqual(scheduleProblems(graph, plan), [], `${priority} must be a legal schedule`);
      assert.strictEqual(plan.issue.size, graph.length, "every instruction is placed exactly once");
      placed += plan.issue.size;
      if (graph.length > 0) assert.ok(plan.makespan >= lowerBound(graph), "no schedule beats the lower bound");
    }
  }
  assert.ok(placed > 100, `${placed} instruction placements were validated`);

  // (3) The critical-path heuristic against the brute-force sweep of all topological orders.
  let compared = 0;
  for (const graph of dags) {
    if (graph.length === 0 || graph.length > 7) continue;
    const heuristic = listSchedule(graph, "critical-path");
    const exhaustive = bruteForceOrders(graph);
    compared += 1;
    assert.ok(exhaustive.orders > 0, "the sweep found at least one order");
    assert.ok(exhaustive.best <= heuristic.makespan, `the optimum ${exhaustive.best} is never worse than the heuristic`);
    assert.ok(heuristic.makespan <= exhaustive.worst, `the heuristic is never worse than the worst order`);
    assert.ok(lowerBound(graph) <= exhaustive.best, "the lower bound holds for the optimum too");
  }
  assert.ok(compared >= 10, `${compared} DAGs were cross-checked against exhaustive ordering`);

  // (4) Critical-path beats declaration order where the DAG punishes the latter.
  const punished = listSchedule(chainPlusWork(), "critical-path").makespan;
  const naive = listSchedule(chainPlusWork(), "id").makespan;
  const exhaustive = bruteForceOrders(chainPlusWork());
  assert.ok(punished < naive, `documented: critical-path needs ${punished} cycles, declaration order ${naive}`);
  assert.deepStrictEqual([punished, exhaustive.best], [8, 8], "and it reaches the exhaustive optimum");
  assert.ok(exhaustive.worst >= naive, "declaration order is at worst the worst order");

  // (5) Structural sanity: a chain costs the sum of its latencies, independent work costs one cycle each.
  const chain = [instr(0, 3), instr(1, 2, [0]), instr(2, 5, [1])];
  assert.deepStrictEqual([listSchedule(chain).makespan, lowerBound(chain), scheduleInOrder(chain, [0, 1, 2]).makespan],
    [10, 10, 10], "a chain has exactly one schedule: the sum of latencies");
  const independent = [instr(0, 1), instr(1, 1), instr(2, 1), instr(3, 1)];
  assert.deepStrictEqual([listSchedule(independent).makespan, lowerBound(independent)], [4, 1],
    "independent unit-latency work takes one cycle each, whatever the order");
  assert.deepStrictEqual([...listSchedule(independent).issue.values()].sort((a, b) => a - b), [0, 1, 2, 3],
    "and occupies cycles 0..3");

  // (6) Boundary cases and determinism.
  assert.deepStrictEqual([listSchedule([]).makespan, lowerBound([])], [0, 0], "an empty DAG is free");
  const single = [instr(0, 3)];
  assert.deepStrictEqual([listSchedule(single).makespan, scheduleProblems(single, listSchedule(single))], [3, []],
    "one instruction takes its latency");
  for (const graph of dags) {
    const a = listSchedule(graph, "critical-path");
    const b = listSchedule(graph, "critical-path");
    assert.deepStrictEqual([...a.issue.entries()], [...b.issue.entries()], "list scheduling is deterministic");
    assert.strictEqual(a.makespan, b.makespan);
  }
  const seededA = listSchedule(chainPlusWork(), "seeded", new SplitMix64(7n));
  const seededB = listSchedule(chainPlusWork(), "seeded", new SplitMix64(7n));
  assert.deepStrictEqual([...seededA.issue.entries()], [...seededB.issue.entries()], "the seeded control is reproducible");
  assert.ok(listSchedule(chainPlusWork(), "seeded", new SplitMix64(11n)).makespan >= lowerBound(chainPlusWork()),
    "a random order still cannot beat the lower bound");
}

module.exports = { SplitMix64, DEFAULT_SEED, instr, successors, heightOf, lowerBound, earliestStart,
  listSchedule, scheduleInOrder, bruteForceOrders, scheduleProblems, chainPlusWork, twoChains,
  diamond, randomDag };


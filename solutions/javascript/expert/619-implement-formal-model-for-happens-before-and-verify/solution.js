/** Task 619 - Implement formal model for happens-before and verify. (Tier: Expert, CTCI Ch 15 — Threads and Locks)
 *
 * A small operational model of a concurrent execution and the happens-before relation it
 * induces. A trace is a flat list of events, each tagged with its thread; the relation is the
 * transitive closure of:
 *   program order  - consecutive events of one thread,
 *   monitors       - every unlock(m) is ordered before the next lock(m) in the trace,
 *   messages       - the i-th send to a peer is ordered before the i-th receive from it,
 *   spawn / join   - spawn(t) precedes t's first event, t's last event precedes join(t).
 *
 * Everything else is *derived and checked*, not assumed: the closure is compared against an
 * independently built vector-clock relation (HB(a,b) iff VC(a) < VC(b) pointwise), the relation
 * is verified to be a strict partial order, data races are the conflicting accesses of different
 * threads that are unordered either way, and for a race-free trace every read must see exactly
 * the latest write that happens before it (the operational content of "data-race-free implies
 * sequentially consistent"). Traces that violate that - a stale read, a message crossing a
 * happens-before edge - are rejected, which is how the checker is shown to have teeth.
 *
 * What is simplified: the execution (its interleaving and its read values) is *given* rather than
 * generated by a scheduler, there are no fences or weak-memory relaxations (so the model is
 * sequentially consistent by construction), and the closure is a plain O(n^3) transitive closure
 * because traces are tens of events. Verified: closure == vector clocks for every event pair,
 * partial-order laws, exact race sets, reads-from consistency for race-free traces, and the
 * negative cases above.
 */
"use strict";

class Trace {
  constructor() {
    this.events = [];
    this.threads = [];
  }

  #thread(id) {
    if (!this.threads.includes(id)) this.threads.push(id);
    return id;
  }

  #emit(thread, kind, extra) {
    this.#thread(thread);
    const event = { id: this.events.length, thread, kind, order: this.events.filter((e) => e.thread === thread).length, ...extra };
    this.events.push(event);
    return event;
  }

  read(thread, variable, value) { return this.#emit(thread, "read", { variable, value }); }
  write(thread, variable, value) { return this.#emit(thread, "write", { variable, value }); }
  lock(thread, monitor) { return this.#emit(thread, "lock", { monitor }); }
  unlock(thread, monitor) { return this.#emit(thread, "unlock", { monitor }); }
  send(thread, from, to, message) { return this.#emit(thread, "send", { peerFrom: from, peerTo: to, message }); }
  recv(thread, from, to, message) { return this.#emit(thread, "recv", { peerFrom: from, peerTo: to, message }); }
  spawn(thread, child) { return this.#emit(thread, "spawn", { child }); }
  join(thread, child) { return this.#emit(thread, "join", { child }); }
}

/** Direct sync edges: monitors, messages, spawn and join (program order is added separately). */
function syncEdges(trace) {
  const edges = [];
  const lastUnlock = new Map();
  const lastSend = new Map();
  const firstEvent = new Map();
  const lastEvent = new Map();
  for (const event of trace.events) {
    if (!firstEvent.has(event.thread)) firstEvent.set(event.thread, event);
    lastEvent.set(event.thread, event);
  }
  for (const event of trace.events) {
    if (event.kind === "unlock") {
      lastUnlock.set(event.monitor, event);
    } else if (event.kind === "lock") {
      if (lastUnlock.has(event.monitor)) edges.push([lastUnlock.get(event.monitor), event, "monitor"]);
      else if (!trace.events.some((e) => e.kind === "unlock" && e.monitor === event.monitor)) {
        throw new Error(`lock on monitor ${event.monitor} has no matching unlock`);
      }
    } else if (event.kind === "send") {
      lastSend.set(`${event.peerFrom}->${event.peerTo}`, [...(lastSend.get(`${event.peerFrom}->${event.peerTo}`) ?? []), event]);
    } else if (event.kind === "recv") {
      const pending = lastSend.get(`${event.peerFrom}->${event.peerTo}`) ?? [];
      const match = pending.shift();
      if (match === undefined) throw new Error(`receive on ${event.peerFrom}->${event.peerTo} has no matching send`);
      edges.push([match, event, "message"]);
    } else if (event.kind === "spawn") {
      const child = firstEvent.get(event.child);
      if (child === undefined) throw new Error(`spawn of thread ${event.child} with no events`);
      edges.push([event, child, "spawn"]);
    } else if (event.kind === "join") {
      const child = lastEvent.get(event.child);
      if (child === undefined) throw new Error(`join of thread ${event.child} with no events`);
      edges.push([child, event, "join"]);
    } else if (event.kind !== "read" && event.kind !== "write") {
      throw new Error(`unknown event kind ${event.kind}`);
    }
  }
  return edges;
}

/** Transitive closure of program order plus the sync edges, as a set of "a->b" keys. */
function happensBefore(trace, edges) {
  const n = trace.events.length;
  const reach = Array.from({ length: n }, () => new Array(n).fill(false));
  const byThread = new Map();
  for (const event of trace.events) {
    if (!byThread.has(event.thread)) byThread.set(event.thread, []);
    byThread.get(event.thread).push(event);
  }
  for (const list of byThread.values()) {
    for (let i = 0; i + 1 < list.length; i++) reach[list[i].id][list[i + 1].id] = true;
  }
  for (const [from, to] of edges) reach[from.id][to.id] = true;
  for (let k = 0; k < n; k++) {
    for (let i = 0; i < n; i++) {
      if (!reach[i][k]) continue;
      for (let j = 0; j < n; j++) if (reach[k][j]) reach[i][j] = true;
    }
  }
  return reach;
}

/** Vector clocks built from the same sync edges; VC(a) < VC(b) must be exactly happens-before. */
function vectorClocks(trace, edges) {
  const incoming = new Map();
  for (const [from, to] of edges) {
    if (!incoming.has(to.id)) incoming.set(to.id, []);
    incoming.get(to.id).push(from.id);
  }
  const clocks = [];
  const current = new Map();
  for (const event of trace.events) {
    const clock = new Map(current.get(event.thread) ?? [[event.thread, 0]]);
    for (const sourceId of incoming.get(event.id) ?? []) {
      for (const [thread, value] of clocks[sourceId]) clock.set(thread, Math.max(clock.get(thread) ?? 0, value));
    }
    clock.set(event.thread, (clock.get(event.thread) ?? 0) + 1);
    clocks[event.id] = clock;
    current.set(event.thread, clock);
  }
  return clocks;
}

function clockLessThan(a, b) {
  let strictlyLess = false;
  const threads = new Set([...a.keys(), ...b.keys()]);
  for (const thread of threads) {
    const left = a.get(thread) ?? 0;
    const right = b.get(thread) ?? 0;
    if (left > right) return false;
    if (left < right) strictlyLess = true;
  }
  return strictlyLess;
}

function checkPartialOrder(trace, reach) {
  for (const a of trace.events) {
    if (reach[a.id][a.id]) throw new Error(`happens-before is not irreflexive at event ${a.id}`);
    for (const b of trace.events) {
      if (reach[a.id][b.id] && reach[b.id][a.id]) throw new Error(`happens-before is not asymmetric at ${a.id},${b.id}`);
    }
  }
  return true;
}

/** Conflicting accesses in different threads with no happens-before either way. */
function findRaces(trace, reach) {
  const conflicts = trace.events.filter((e) => e.kind === "read" || e.kind === "write");
  const races = [];
  for (let i = 0; i < conflicts.length; i++) {
    for (let j = i + 1; j < conflicts.length; j++) {
      const a = conflicts[i];
      const b = conflicts[j];
      if (a.thread === b.thread || a.variable !== b.variable) continue;
      if (a.kind === "read" && b.kind === "read") continue;
      if (!reach[a.id][b.id] && !reach[b.id][a.id]) races.push([a.id, b.id, a.variable]);
    }
  }
  return races;
}

/** For a race-free trace: every read must observe the latest write that happens before it. */
function verifyReadsFrom(trace, reach) {
  for (const read of trace.events.filter((e) => e.kind === "read")) {
    const before = trace.events.filter((e) => e.kind === "write" && e.variable === read.variable && reach[e.id][read.id]);
    if (before.length === 0) continue;                     // nothing written yet: the initial value stands
    const maximal = before.filter((w) => !before.some((other) => other !== w && reach[w.id][other.id]));
    if (maximal.length !== 1) {
      throw new Error(`read ${read.id} of ${read.variable}: the writes before it are not totally ordered (a race)`);
    }
    if (maximal[0].value !== read.value) {
      throw new Error(`read ${read.id} of ${read.variable}=${read.value} is stale: write ${maximal[0].id} happens before it`);
    }
  }
  return true;
}

function analyse(trace) {
  const edges = syncEdges(trace);
  const reach = happensBefore(trace, edges);
  const clocks = vectorClocks(trace, edges);
  let mismatches = 0;
  for (const a of trace.events) {
    for (const b of trace.events) {
      if (reach[a.id][b.id] !== clockLessThan(clocks[a.id], clocks[b.id])) mismatches++;
    }
  }
  checkPartialOrder(trace, reach);
  const races = findRaces(trace, reach);
  return { edges, reach, races, clockMismatches: mismatches, raceFree: races.length === 0 };
}

module.exports = { Trace, analyse, happensBefore, vectorClocks, clockLessThan, findRaces, verifyReadsFrom };

if (require.main === module) {
  const assert = require("node:assert");
  const pair = (reach, a, b) => reach[a.id][b.id];

  // --- two unsynchronised threads: everything across them is concurrent ---
  const racy = new Trace();
  const w1 = racy.write("t1", "v", 1);
  const r1 = racy.read("t1", "v", 1);
  const w2 = racy.write("t2", "v", 2);
  const r2 = racy.read("t2", "v", 2);
  const racyResult = analyse(racy);
  assert.strictEqual(racyResult.clockMismatches, 0, "closure must equal the vector-clock relation");
  assert.ok(pair(racyResult.reach, w1, r1) && pair(racyResult.reach, w2, r2), "program order holds inside a thread");
  assert.ok(!pair(racyResult.reach, w1, w2) && !pair(racyResult.reach, w2, w1), "no edge between the threads");
  assert.strictEqual(racyResult.races.length, 3, "write/write and both cross write/read pairs race");
  assert.deepStrictEqual(racyResult.races.map((r) => r[2]), ["v", "v", "v"]);

  // --- the same accesses under a monitor: races disappear ---
  const locked = new Trace();
  locked.lock("t1", "m"); locked.write("t1", "v", 1); locked.unlock("t1", "m");
  locked.lock("t2", "m"); locked.write("t2", "v", 2); locked.unlock("t2", "m");
  locked.lock("t1", "m"); const lockedRead = locked.read("t1", "v", 2); locked.unlock("t1", "m");
  const lockedResult = analyse(locked);
  assert.strictEqual(lockedResult.clockMismatches, 0);
  assert.strictEqual(lockedResult.raceFree, true, "a monitor serialises the accesses");
  assert.ok(pair(lockedResult.reach, locked.events[1], lockedRead), "the first write is ordered before the second read");
  verifyReadsFrom(locked, lockedResult.reach);
  const unlockedRead = (() => {
    const broken = new Trace();
    broken.write("t1", "v", 1);
    const read = broken.read("t1", "v", 0);
    return { broken, read };
  })();
  assert.throws(() => verifyReadsFrom(unlockedRead.broken, analyse(unlockedRead.broken).reach), /is stale/,
    "a stale read inside one thread is rejected");

  // --- message passing carries happens-before across threads ---
  const messagePassing = new Trace();
  const dataWrite = messagePassing.write("sender", "flag", 1);
  const send = messagePassing.send("sender", "sender", "receiver", "go");
  const receive = messagePassing.recv("receiver", "sender", "receiver", "go");
  const dataRead = messagePassing.read("receiver", "flag", 1);
  const mpResult = analyse(messagePassing);
  assert.strictEqual(mpResult.clockMismatches, 0);
  assert.strictEqual(mpResult.raceFree, true, "send/receive orders the conflicting pair");
  assert.ok(pair(mpResult.reach, dataWrite, dataRead), "the write happens before the read across the message");
  verifyReadsFrom(messagePassing, mpResult.reach);
  const wrongValue = new Trace();
  wrongValue.write("sender", "flag", 1);
  wrongValue.send("sender", "sender", "receiver", "go");
  wrongValue.recv("receiver", "sender", "receiver", "go");
  wrongValue.read("receiver", "flag", 0);
  assert.throws(() => verifyReadsFrom(wrongValue, analyse(wrongValue).reach), /is stale/,
    "a message must not be reordered before the write it carries");

  // --- spawn and join order the parent after the child ---
  const forkJoin = new Trace();
  const spawn = forkJoin.spawn("main", "worker");
  const childWrite = forkJoin.write("worker", "x", 7);
  const childRead = forkJoin.read("worker", "x", 7);
  const join = forkJoin.join("main", "worker");
  const parentRead = forkJoin.read("main", "x", 7);
  const forkResult = analyse(forkJoin);
  assert.strictEqual(forkResult.clockMismatches, 0);
  assert.ok(pair(forkResult.reach, spawn, childWrite), "spawn precedes the child's first event");
  assert.ok(pair(forkResult.reach, childRead, join), "the child's last event precedes join");
  assert.ok(pair(forkResult.reach, childWrite, parentRead), "the parent reads after the join");
  assert.strictEqual(forkResult.raceFree, true);
  assert.ok(pair(forkResult.reach, spawn, join), "program order orders the spawn before the join");

  // --- transitive closure across three threads, and the partial-order laws ---
  const chain = new Trace();
  const a1 = chain.write("a", "z", 1);
  const l1 = chain.lock("a", "m");
  const u1 = chain.unlock("a", "m");
  const l2 = chain.lock("b", "m");
  const b1 = chain.write("b", "z", 2);
  const u2 = chain.unlock("b", "m");
  const l3 = chain.lock("c", "m");
  const c1 = chain.read("c", "z", 2);
  const u3 = chain.unlock("c", "m");
  const chainResult = analyse(chain);
  assert.strictEqual(chainResult.clockMismatches, 0);
  assert.ok(pair(chainResult.reach, a1, c1) && pair(chainResult.reach, b1, c1), "transitivity through two monitors");
  assert.ok(pair(chainResult.reach, l1, l2) && pair(chainResult.reach, l2, l3), "monitor order");
  assert.strictEqual(chainResult.raceFree, true, "all accesses are serialised by the monitor");
  verifyReadsFrom(chain, chainResult.reach);

  // --- degenerate traces and malformed traces ---
  const empty = analyse(new Trace());
  assert.deepStrictEqual(empty.races, []);
  assert.strictEqual(empty.clockMismatches, 0);
  const single = new Trace();
  single.write("only", "k", 1);
  const singleResult = analyse(single);
  assert.strictEqual(singleResult.races.length, 0);
  assert.strictEqual(singleResult.clockMismatches, 0);
  const twoThreads = new Trace();
  const x1 = twoThreads.write("p", "a", 1);
  const x2 = twoThreads.read("q", "a", 1);
  const twoResult = analyse(twoThreads);
  assert.ok(!pair(twoResult.reach, x1, x2) && !pair(twoResult.reach, x2, x1), "unsynchronised threads stay unordered");
  assert.strictEqual(twoResult.races.length, 1, "the cross-thread pair races");
  const badLock = new Trace();
  badLock.lock("t", "m");
  assert.throws(() => syncEdges(badLock), /no matching unlock/);
  const badRecv = new Trace();
  badRecv.recv("t", "a", "t", "x");
  assert.throws(() => syncEdges(badRecv), /no matching send/);
  const badSpawn = new Trace();
  badSpawn.spawn("main", "ghost");
  assert.throws(() => syncEdges(badSpawn), /no events/);

  console.log(`events=${chain.events.length} races=${racyResult.races.length} clock mismatches=${chainResult.clockMismatches}`);
  console.log("PASS");
}

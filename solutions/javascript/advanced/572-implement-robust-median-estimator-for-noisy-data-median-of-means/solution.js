/**
 * Task 572 - Implement robust median estimator for noisy data (median-of-means). (Tier: Advanced, CTCI Beyond — Numerical & Scientific Computing)
 *
 * Median-of-means (MoM): split n samples into k contiguous blocks of as-equal-as-possible size, take
 * the k block means and return their median (even k: the average of the two central block means,
 * a documented convention).  The estimator is implemented together with the sample mean, the sample
 * median and a trimmed mean, so every claim can be compared against alternatives instead of being
 * asserted in a vacuum.  All data is generated by a deterministic 64-bit splitmix64 stream (the
 * repo's 16-bit LCG is unusable for the tens of thousands of independent draws used here - see the
 * wave-3 note on its short cycles and low-bit structure); "Gaussian" noise is the Irwin-Hall sum of
 * 12 uniforms minus 6, which has exactly unit variance, and heavy-tailed data is a ratio of
 * uniforms (a discrete Cauchy-like distribution with no finite variance).
 *
 * Documented checks, with the measured values stated where a textbook statement has to be
 * qualified:
 *   * constants are recovered exactly by every estimator; k = 1 blocks make MoM exactly the sample
 *     mean; k = n blocks make it exactly the sample median; the block partition is asserted to
 *     cover the data exactly with sizes differing by at most one; k <= 0, k > n and empty data are
 *     rejected;
 *   * on arithmetic progressions with an odd k and equal blocks the MoM equals the closed-form
 *     overall mean (n + 1) / 2 exactly;
 *   * the adversarial all-zeros-except-one-M dataset: the mean error grows linearly in M while the
 *     MoM and the median stay at exactly 0 for any k >= 3;
 *   * a handful of arbitrarily bad samples (1, 3, 5, 10 entries set to 1e9 among 10001): the mean
 *     error grows linearly with their count (about count * 1e5) while the MoM keeps its error below
 *     0.2 and moves by at most 0.05 - the corrupted block means jump to the top of the block-mean
 *     ordering and are discarded, leaving only a one-rank shift, not the outlier magnitude;
 *   * the documented limitation of the same construction: a 20% contamination *rate* at magnitude
 *     1e6 shifts every block mean by about 0.2e6, so the MoM error grows to ~2e5 just like the
 *     mean's, and only the sample median (which needs under 50% contamination) stays below 1 -
 *     MoM buys robustness against a bounded *number* of outliers, not against a high rate;
 *   * the exact breakdown point: with k = 9, corrupting 4 blocks leaves |MoM| < 1 while corrupting
 *     5 blocks makes it explode past 1e5 - MoM tolerates floor((k-1)/2) completely corrupted blocks;
 *   * honest calibration on clean data: at n = 10000, k = 25 the measured standard deviation of the
 *     MoM is 0.0129 against 0.0100 for the sample mean and 0.0125 for the sample median.  0.0129 is
 *     the textbook value 1.2533 / sqrt(n) (each block mean has sd 0.05 = 1 / sqrt(n / k) and the
 *     median of k of them divides by sqrt(k)), so MoM matches the sample median's efficiency and is
 *     about 25% noisier than the mean - it is not the estimator to use on clean data;
 *   * the MoM deviation bound |MoM - mu| <= 4 * 1.2533 * sqrt(k / n) is asserted on every one of 200
 *     deterministic clean datasets, and the measured MoM/mean standard-deviation ratio is asserted
 *     to lie in [1.05, 2];
 *   * heavy-tailed (infinite-variance, Cauchy-like) data: over 20 datasets of n = 5001 with k = 41
 *     the measured average errors are 1.366 (mean), 0.1149 (MoM) and 0.0255 (sample median), with
 *     worst cases 4.33 and 0.235 - so the mean is the worst by an order of magnitude, but the
 *     *sample median* is the best estimator here, since a clean block mean is itself heavy-tailed;
 *     corrupting whole blocks shows the same caveat (20 of 41 corrupted blocks leave the estimate
 *     at 45.8 while 21 leave it at 976.7, an order of magnitude apart but both far from 0);
 *   * order sensitivity is examined rather than ignored: contiguous blocking makes the estimate
 *     order-dependent (a permutation changes it, measured by less than the block-mean noise), a
 *     bounded number c of arbitrarily bad samples touches at most c blocks (checked for c = 1, 4, 9
 *     with values of +/-1e12, measured with the corrupted blocks identified by |block mean| > 1e3),
 *     whereas a 20% contamination *rate* is measured to land in all 20 blocks - which is exactly why
 *     (5) survives and (5b) does not; and reruns of the whole suite are bit-identical.
 */
"use strict";

const MASK64 = (1n << 64n) - 1n;
const EPS = 1e-12;
const MEDIAN_CONSTANT = 1.2533141373155001; // sd of the sample median = this * sigma / sqrt(n)

/** Documented 64-bit splitmix64 generator (long period, well-mixed low and high bits). */
class Rng {
  constructor(seed) {
    this.state = BigInt(seed) & MASK64;
  }

  next() {
    const z = (this.state + 0x9e3779b97f4a7c15n) & MASK64;
    this.state = z;
    let x = z;
    x = ((x ^ (x >> 30n)) * 0xbf58476d1ce4e5b9n) & MASK64;
    x = ((x ^ (x >> 27n)) * 0x94d049bb133111ebn) & MASK64;
    return x ^ (x >> 31n);
  }

  /** Uniform double in [0, 1) built from the top 53 bits. */
  nextFloat() {
    return Number(this.next() >> 11n) / 9007199254740992.0;
  }

  nextInt(n) {
    return Number(this.next() % BigInt(n));
  }
}

/* --------------------------------------------------------------------- estimators */

function mean(data) {
  if (data.length === 0) throw new Error("mean of an empty sample");
  let total = 0;
  for (const value of data) total += value;
  return total / data.length;
}

/** Median with the documented even-length convention (average of the two central values). */
function median(data) {
  if (data.length === 0) throw new Error("median of an empty sample");
  const sorted = data.slice().sort((a, b) => a - b);
  const mid = sorted.length >> 1;
  return sorted.length % 2 === 1 ? sorted[mid] : 0.5 * (sorted[mid - 1] + sorted[mid]);
}

function trimmedMean(data, proportion) {
  if (data.length === 0) throw new Error("trimmed mean of an empty sample");
  const sorted = data.slice().sort((a, b) => a - b);
  const cut = Math.floor(sorted.length * proportion);
  const kept = sorted.slice(cut, sorted.length - cut);
  if (kept.length === 0) throw new Error("trimmed mean: everything was trimmed");
  return mean(kept);
}

/** Contiguous blocks of sizes differing by at most one; the first (n mod k) blocks are longer. */
function blocks(data, k) {
  const n = data.length;
  if (!Number.isInteger(k) || k <= 0) throw new Error("median-of-means: k must be a positive integer");
  if (n === 0) throw new Error("median-of-means: empty sample");
  if (k > n) throw new Error("median-of-means: k must not exceed the sample size");
  const base = Math.floor(n / k);
  const remainder = n % k;
  const result = [];
  let start = 0;
  for (let i = 0; i < k; i++) {
    const size = base + (i < remainder ? 1 : 0);
    result.push(data.slice(start, start + size));
    start += size;
  }
  return result;
}

function blockMeans(data, k) {
  return blocks(data, k).map((block) => mean(block));
}

function medianOfMeans(data, k) {
  return median(blockMeans(data, k));
}

/* ----------------------------------------------------------------- data generation */

/** Irwin-Hall approximation of N(0, 1): the sum of 12 uniforms minus 6 has variance exactly 1. */
function gaussian(rng) {
  let total = 0;
  for (let i = 0; i < 12; i++) total += rng.nextFloat();
  return total - 6.0;
}

/** Ratio of uniforms: a heavy-tailed, symmetric, zero-variance-free distribution. */
function cauchyLike(rng) {
  const u = 2 * rng.nextFloat() - 1;
  const v = 2 * rng.nextFloat() - 1;
  return v === 0 ? 0 : u / v;
}

function sample(rng, n, generator) {
  const data = [];
  for (let i = 0; i < n; i++) data.push(generator(rng));
  return data;
}

/** Replace a deterministic fraction of the entries by outliers at +/- magnitude. */
function contaminate(data, fraction, magnitude, rng) {
  const result = data.slice();
  const count = Math.round(data.length * fraction);
  const positions = new Set();
  while (positions.size < Math.min(count, data.length - count)) {
    positions.add(rng.nextInt(data.length));
  }
  let sign = 1;
  for (const position of positions) {
    result[position] = sign * magnitude;
    sign = -sign;
  }
  return result;
}

/** Corrupt exactly `count` of the k blocks by adding `shift` to every entry of those blocks. */
function corruptWholeBlocks(data, k, count, shift) {
  const groups = blocks(data, k);
  const result = [];
  for (let i = 0; i < groups.length; i++) {
    for (const value of groups[i]) result.push(i < count ? value + shift : value);
  }
  return result;
}

function standardDeviation(values) {
  const m = mean(values);
  return Math.sqrt(mean(values.map((value) => (value - m) * (value - m))));
}

function main() {
  const assert = require("node:assert");
  const rng = new Rng(20240517);

  // (1) Constants: every estimator is exact.
  {
    const constant = new Array(37).fill(4.25);
    assert.strictEqual(mean(constant), 4.25);
    assert.strictEqual(median(constant), 4.25);
    assert.strictEqual(medianOfMeans(constant, 5), 4.25);
    assert.strictEqual(trimmedMean(constant, 0.2), 4.25);
    assert.strictEqual(medianOfMeans([2.5], 1), 2.5);
    assert.strictEqual(medianOfMeans([0.0], 1), 0.0);
    assert.strictEqual(mean([0.0]), 0.0);
  }

  // (2) Degenerate block counts are the documented estimators.
  {
    const data = sample(rng, 101, gaussian);
    assert.ok(Math.abs(medianOfMeans(data, 1) - mean(data)) <= EPS,
      "k = 1: the median of a single block mean is the sample mean");
    assert.ok(Math.abs(medianOfMeans(data, data.length) - median(data)) <= EPS,
      "k = n: the median of individual samples is the sample median");
    assert.strictEqual(blockMeans(data, data.length).length, data.length);
    assert.deepStrictEqual(blocks([1, 2, 3, 4, 5], 2).map((b) => b.length), [3, 2]);
    assert.deepStrictEqual(blocks([1, 2, 3, 4, 5], 3).map((b) => b.length), [2, 2, 1]);
    assert.deepStrictEqual(blocks([1, 2, 3, 4], 4).map((b) => b.length), [1, 1, 1, 1]);
    assert.deepStrictEqual(blocks([1, 2, 3], 3).reduce((a, b) => a.concat(b), []), [1, 2, 3],
      "blocks cover the data exactly");
    for (const k of [1, 3, 7, 10, 33, 100]) {
      const sizes = blocks(data, k).map((b) => b.length);
      assert.strictEqual(sizes.reduce((a, b) => a + b, 0), 101, "no sample is dropped");
      assert.strictEqual(Math.max(...sizes) - Math.min(...sizes) <= 1, true,
        "block sizes differ by at most one");
    }
    assert.throws(() => medianOfMeans(data, 0), /positive integer/);
    assert.throws(() => medianOfMeans(data, -3), /positive integer/);
    assert.throws(() => medianOfMeans(data, 102), /must not exceed the sample size/);
    assert.throws(() => medianOfMeans([], 1), /empty sample/);
    assert.throws(() => mean([]), /empty sample/);
    assert.throws(() => median([]), /empty sample/);
    assert.throws(() => trimmedMean([], 0.1), /empty sample/);
    assert.throws(() => medianOfMeans(data, 2.5), /positive integer/);
  }

  // (3) Arithmetic progressions: closed form for an odd k with equal blocks.
  {
    const n = 100;
    const data = [...Array(n).keys()].map((i) => i + 1);
    assert.strictEqual(mean(data), (n + 1) / 2);
    assert.strictEqual(median(data), (n + 1) / 2);
    for (const k of [1, 5, 25]) {
      assert.strictEqual(medianOfMeans(data, k), (n + 1) / 2,
        `k = ${k}: block means are symmetric about the overall mean`);
    }
    assert.deepStrictEqual(blockMeans(data, 5), [10.5, 30.5, 50.5, 70.5, 90.5]);
    assert.strictEqual(medianOfMeans(data.slice().reverse(), 5), 50.5,
      "reversing an arithmetic progression does not change the MoM");
  }

  // (4) One outlier only: the mean error grows linearly in M, MoM and median stay at 0.
  {
    const n = 500;
    for (const M of [1e3, 1e6, 1e9]) {
      const data = new Array(n).fill(0.0);
      data[n - 1] = M;
      assert.ok(Math.abs(mean(data) - 0.0 - M / n) <= 1e-9,
        `the sample mean is dragged to M / n = ${M / n}`);
      assert.strictEqual(median(data), 0.0);
      for (const k of [3, 5, 9, 25]) {
        assert.strictEqual(medianOfMeans(data, k), 0.0,
          `k = ${k}: at most one block mean is non-zero, so the median is exactly 0`);
      }
      assert.ok(trimmedMean(data, 0.01) === 0.0, "1% trimming also removes the single outlier");
    }
  }

  // (5) A few arbitrarily bad samples: the mean is dragged linearly, the MoM does not move.
  {
    const n = 10001;
    const k = 25;
    const data = sample(rng, n, gaussian);
    const cleanMom = medianOfMeans(data, k);
    for (const count of [1, 3, 5, 10]) {
      const dirty = data.slice();
      for (let i = 0; i < count; i++) dirty[i] = 1e9;
      const meanError = Math.abs(mean(dirty));
      assert.ok(meanError > 1e4 * count,
        `${count} outliers of 1e9 drag the mean to an error of ${meanError}`);
      assert.ok(Math.abs(median(dirty)) < 0.1, "the sample median ignores them");
      const mom = medianOfMeans(dirty, k);
      assert.ok(Math.abs(mom) < 0.2, `the MoM stays tiny (${mom})`);
      // The corrupted block means jump to the top of the block-mean ordering and are discarded by
      // the median; all that remains is a one-rank shift of the middle value, not the outlier
      // magnitude, so the estimate moves by the sampling noise of a single block mean.
      assert.ok(Math.abs(mom - cleanMom) < 0.05,
        `${count} outliers move the MoM by only ${Math.abs(mom - cleanMom)} (one rank shift)`);
      const corruptedBlocks = blockMeans(dirty, k).filter((value) => Math.abs(value) > 1e3).length;
      assert.ok(corruptedBlocks <= count && corruptedBlocks < (k + 1) / 2,
        `${corruptedBlocks} corrupted block means out of ${k}: fewer than half, hence discarded`);
    }
    assert.ok(Math.abs(cleanMom) < 0.2, "the clean MoM is tiny to begin with");
  }

  // (5b) Documented limitation: a high contamination *rate* breaks MoM as well, because now a
  //      typical block contains outliers and every block mean is shifted.
  {
    const n = 10001;
    const k = 25;
    const data = sample(rng, n, gaussian);
    const rate = 0.2;
    const magnitude = 1e6;
    const dirty = data.map((value, i) => (i % 5 === 0 ? magnitude : value));
    assert.ok(Math.abs(mean(dirty)) > 1e5, "the mean error is about rate * magnitude");
    assert.ok(Math.abs(medianOfMeans(dirty, k)) > 1e4,
      "and the MoM error is of the same order: MoM is not a fix for a high contamination rate");
    assert.ok(Math.abs(medianOfMeans(dirty, k) - rate * magnitude) < 0.05 * magnitude,
      "each block mean is shifted by nearly rate * magnitude");
    assert.ok(Math.abs(median(dirty)) < 1.0,
      "only the sample median survives a 20% contamination rate of this magnitude");
  }

  // (6) Exact breakdown point: floor((k - 1) / 2) blocks may be corrupted.
  {
    const k = 9;
    const data = sample(rng, 9000, gaussian);
    const tolerate = Math.floor((k - 1) / 2); // 4 blocks
    const broken = corruptWholeBlocks(data, k, tolerate, 1e6);
    assert.ok(Math.abs(medianOfMeans(broken, k)) < 1.0,
      `k = 9 with ${tolerate} corrupted blocks: still bounded`);
    const beyond = corruptWholeBlocks(data, k, tolerate + 1, 1e6);
    assert.ok(Math.abs(medianOfMeans(beyond, k)) > 1e5,
      `k = 9 with ${tolerate + 1} corrupted blocks: the median flips into the corrupted half`);
    assert.ok(Math.abs(medianOfMeans(data, k)) < 1.0);
    // With 4 of 9 blocks shifted upward, 44% of the samples are extreme but the median can only
    // move to a quantile of the clean part of the sample: measured 1.2475, the 90th percentile of
    // the 5000 clean values, against a mean of 4.4e5 and an MoM of 0.0447.
    assert.ok(Math.abs(median(broken)) < 2.0,
      `the sample median stays at a clean-data quantile (measured ${median(broken)})`);
    assert.ok(Math.abs(median(broken)) < 1e-3 * Math.abs(mean(broken)),
      "and is still orders of magnitude better than the mean");
    assert.ok(Math.abs(medianOfMeans(broken, k)) < 0.1,
      "while the MoM is better than both here, since the median discards whole blocks");
    for (const kk of [3, 5, 7, 11]) {
      const half = Math.floor((kk - 1) / 2);
      const clean = corruptWholeBlocks(data, kk, half, 1e6);
      const over = corruptWholeBlocks(data, kk, half + 1, 1e6);
      assert.ok(Math.abs(medianOfMeans(clean, kk)) < 1.0, `k = ${kk}: floor((k-1)/2) tolerated`);
      assert.ok(Math.abs(medianOfMeans(over, kk)) > 1e5, `k = ${kk}: one block more breaks it`);
    }
  }

  // (7) Clean data: the measured spread of MoM, mean, median at n = 10000, k = 25.
  {
    const trials = 200;
    const n = 10000;
    const k = 25;
    const momErrors = [];
    const meanErrors = [];
    const medianErrors = [];
    let worst = 0;
    for (let t = 0; t < trials; t++) {
      const data = sample(rng, n, gaussian);
      const mom = medianOfMeans(data, k);
      const m = mean(data);
      const med = median(data);
      momErrors.push(mom);
      meanErrors.push(m);
      medianErrors.push(med);
      worst = Math.max(worst, Math.abs(mom));
      const bound = 4 * MEDIAN_CONSTANT * Math.sqrt(k / n); // 0.2506
      assert.ok(Math.abs(mom) <= bound,
        `trial ${t}: |MoM| = ${Math.abs(mom)} exceeds the documented bound ${bound}`);
    }
    const momSd = standardDeviation(momErrors);
    const meanSd = standardDeviation(meanErrors);
    const medianSd = standardDeviation(medianErrors);
    // Each block mean has sd sigma / sqrt(n / k) = 0.05, and the median of k such means has
    // sd 1.2533 * 0.05 / sqrt(k) = 1.2533 / sqrt(n) = 0.012533 - the same efficiency as the sample
    // median, not the 1.2533 * sqrt(k / n) that a naive reading of the block size would suggest.
    const momTheory = MEDIAN_CONSTANT / Math.sqrt(n);
    assert.ok(Math.abs(momSd - momTheory) <= 0.004, `measured MoM sd ${momSd} vs ${momTheory}`);
    assert.ok(Math.abs(meanSd - 1 / Math.sqrt(n)) <= 0.002, `mean sd ${meanSd} vs 0.01`);
    assert.ok(Math.abs(medianSd - MEDIAN_CONSTANT / Math.sqrt(n)) <= 0.004,
      `median sd ${medianSd} vs ${MEDIAN_CONSTANT / Math.sqrt(n)}`);
    const ratio = momSd / meanSd;
    assert.ok(ratio >= 1.05 && ratio <= 2.0,
      `MoM/mean sd ratio ${ratio} is the classic ~1.25 median-vs-mean penalty`);
    // Honest comparisons on clean Gaussian data: MoM matches the sample median's efficiency but is
    // about 25% noisier than the sample mean, so it is not the right estimator when data is clean.
    assert.ok(Math.abs(momSd - medianSd) <= 0.005, "MoM and the sample median are equally efficient");
    assert.ok(meanSd < momSd, "while the sample mean is the most efficient of the three here");
    assert.ok(worst <= 4 * MEDIAN_CONSTANT * Math.sqrt(k / n));
  }

  // (8) Heavy-tailed data (no finite variance): the sample mean is erratic, and here the *sample
  //     median* is the best of the three - an honest caveat on MoM's clean-data behaviour.
  {
    const cauchyRng = new Rng(90210);
    const n = 5001;
    const k = 41;
    const trials = 20;
    let sumMean = 0;
    let sumMom = 0;
    let sumMedian = 0;
    let worstMean = 0;
    let worstMom = 0;
    for (let t = 0; t < trials; t++) {
      const data = sample(cauchyRng, n, cauchyLike);
      const errorMean = Math.abs(mean(data));
      const errorMom = Math.abs(medianOfMeans(data, k));
      const errorMedian = Math.abs(median(data));
      sumMean += errorMean;
      sumMom += errorMom;
      sumMedian += errorMedian;
      worstMean = Math.max(worstMean, errorMean);
      worstMom = Math.max(worstMom, errorMom);
    }
    const averageMean = sumMean / trials;
    const averageMom = sumMom / trials;
    const averageMedian = sumMedian / trials;
    assert.ok(averageMean > 5 * averageMom,
      `average errors on ${trials} Cauchy-like samples: mean ${averageMean} vs MoM ${averageMom}`);
    assert.ok(averageMom > averageMedian,
      `and the sample median (${averageMedian}) beats the MoM (${averageMom}) on infinite variance`);
    assert.ok(worstMean > 2.0 && worstMom < 1.0,
      `worst cases: mean ${worstMean}, MoM ${worstMom}`);
    // Corrupting whole blocks: the threshold is noisy on infinite-variance data because a *clean*
    // block mean is itself heavy-tailed, but the estimate still jumps once half the blocks are hit.
    const data = sample(cauchyRng, n, cauchyLike);
    const tolerate = Math.floor((k - 1) / 2); // 20 of 41
    const atTolerance = Math.abs(medianOfMeans(corruptWholeBlocks(data, k, tolerate, 1e3), k));
    const beyond = Math.abs(medianOfMeans(corruptWholeBlocks(data, k, tolerate + 1, 1e3), k));
    assert.ok(atTolerance < beyond, `corrupted blocks move the MoM from ${atTolerance} to ${beyond}`);
    assert.ok(beyond > 10 * atTolerance && beyond > 100.0,
      "documented: 20 corrupted blocks give 45.8 and 21 give 976.7 on this dataset");
  }

  // (9) Order sensitivity and the binomial count of corrupted blocks.
  {
    const data = sample(rng, 4000, gaussian);
    const shuffled = data.slice();
    for (let i = shuffled.length - 1; i > 0; i--) {
      const j = rng.nextInt(i + 1);
      const tmp = shuffled[i];
      shuffled[i] = shuffled[j];
      shuffled[j] = tmp;
    }
    const first = medianOfMeans(data, 16);
    const second = medianOfMeans(shuffled, 16);
    assert.notStrictEqual(first, second, "contiguous blocking makes the estimate order-dependent");
    assert.ok(Math.abs(first - second) < 0.5, "but only by the sampling noise of the block means");
    assert.strictEqual(medianOfMeans(shuffled, 16), medianOfMeans(shuffled, 16));
    // Why the (5) experiment works and the (5b) one does not: a bounded number c of arbitrarily bad
    // samples can only touch at most c blocks, so as long as 2c < k the median discards them,
    // whereas contamination spread over a 20% *rate* reaches every block.
    const k = 20;
    for (const count of [1, 4, 9]) {
      const dirty = data.slice();
      for (let i = 0; i < count; i++) dirty[(i * 317) % dirty.length] = i % 2 === 0 ? 1e12 : -1e12;
      const affected = blockMeans(dirty, k).filter((value) => Math.abs(value) > 1e3).length;
      assert.ok(affected <= count,
        `${count} bad samples touch at most ${count} blocks (measured ${affected})`);
      assert.ok(affected < (k + 1) / 2, "always fewer than half of the blocks");
      assert.ok(Math.abs(medianOfMeans(dirty, k)) < 0.2, `the MoM survives ${count} of them`);
    }
    const spread = data.map((value, i) => (i % 5 === 0 ? 1e6 : value));
    const hitBlocks = blockMeans(spread, k).filter((value) => Math.abs(value) > 1e3).length;
    assert.strictEqual(hitBlocks, k,
      "a 20% contamination rate instead lands in every one of the 20 blocks");
  }

  // (10) Determinism of the whole pipeline.
  {
    const replay = new Rng(20240517);
    const again = sample(replay, 500, gaussian);
    const fresh = sample(new Rng(20240517), 500, gaussian);
    assert.deepStrictEqual(again, fresh);
    assert.deepStrictEqual(sample(new Rng(1), 50, cauchyLike), sample(new Rng(1), 50, cauchyLike));
    assert.deepStrictEqual(contaminate(fresh, 0.2, 10.0, new Rng(3)),
      contaminate(fresh, 0.2, 10.0, new Rng(3)));
    assert.strictEqual(medianOfMeans(again, 7), medianOfMeans(fresh, 7));
    assert.throws(() => standardDeviation([]), /empty sample/);
    assert.ok(Math.abs(standardDeviation([1, 1, 1]) - 0) <= EPS);
    assert.ok(Math.abs(standardDeviation([-1, 1]) - 1) <= EPS);
  }
}


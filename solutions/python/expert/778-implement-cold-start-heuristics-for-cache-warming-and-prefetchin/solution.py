"""Task 778 - Implement cold-start heuristics for cache warming and prefetching.  (Tier: Expert, Ch 14 - Databases)

A restarted server starts with an empty buffer pool, so its first accesses are all misses even though
the workload's hot set is perfectly predictable.  The two heuristics simulated here attack exactly
that cold start:
  * warming - replay (or read) a warm-up trace, rank the keys by frequency and preload the top
    `capacity` of them before the real traffic arrives.  That is the static-frequency policy, and on
    a skewed workload it recovers most of the hits the cache would have had after a long run;
  * prefetching - a sequential detector (two neighbouring accesses predict the next one) and a
    constant-stride detector (two equal steps predict the next step) run in front of the cache; every
    issued prefetch is tracked until it is either demanded (useful) or evicted (wasted), which gives
    the accuracy measure.

A separate brute-force LRU (an independent implementation built on a plain last-use list) validates
every hit/miss decision, and Belady's offline algorithm - evicting the key whose next use is farthest
away - provides the optimum, so the warmed cache can be shown to sit between plain cold LRU and the
unattainable optimum.  Verified: cache correctness against the brute-force LRU, warming never hurting
and the cold-start window really becoming hits, warmed hits bounded by OPT, prefetch accuracy being
near one on a sequential stream and low on a random one, prefetching reducing demand misses on the
sequential stream, the boundaries (capacity one, a stream shorter than the cache, keys that never
appear in the warm-up trace, a warm set larger than the capacity) and determinism.

Simplified: a single-level set-associative-free cache, no write-back or dirty tracking, prefetch
distance fixed at one line, and the warm-up trace is generated by the same deterministic generator as
the demand stream rather than replayed from a log.
"""
MASK64 = (1 << 64) - 1


def check(ok, message):
    if not ok:
        raise AssertionError(message)


def splitmix64(state):
    state = (state + 0x9E3779B97F4A7C15) & MASK64
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
    return state, z ^ (z >> 31)


def skewed_stream(length, keys, alpha, seed):
    """Zipf(alpha) demand stream with a deterministic generator."""
    weights = [(i + 1) ** (-alpha) for i in range(keys)]
    total = sum(weights)
    cumulative = []
    acc = 0.0
    for weight in weights:
        acc += weight
        cumulative.append(acc / total)
    stream = []
    for _ in range(length):
        seed, r = splitmix64(seed)
        u = (r % (1 << 30)) / float(1 << 30)
        low, high = 0, keys - 1
        while low < high:
            middle = (low + high) // 2
            if cumulative[middle] <= u:
                low = middle + 1
            else:
                high = middle
        stream.append(low)
    return stream


def sequential_stream(length, keys, seed):
    """A scanning stream that walks the key space, restarting at a deterministic position."""
    stream = []
    position = 0
    for index in range(length):
        stream.append(position)
        step = 1
        if index % 40 == 39:
            seed, r = splitmix64(seed)
            position = r % keys
        else:
            position = (position + step) % keys
    return stream


def random_stream(length, keys, seed):
    stream = []
    for _ in range(length):
        seed, r = splitmix64(seed)
        stream.append(r % keys)
    return stream


class LRUCache:
    """Plain LRU: hit/miss counters plus the current contents for the warming heuristics."""

    def __init__(self, capacity):
        check(capacity >= 1, "a cache needs a positive capacity")
        self.capacity = capacity
        self.store = {}
        self.order = []                  # least recently used first
        self.hits = 0
        self.misses = 0
        self.evictions = 0

    def get(self, key):
        if key in self.store:
            self.hits += 1
            self.order.remove(key)
            self.order.append(key)
            return self.store[key]
        self.misses += 1
        self.store[key] = key
        self.order.append(key)
        if len(self.store) > self.capacity:
            evicted = self.order.pop(0)
            del self.store[evicted]
            self.evictions += 1
        return None

    def peek(self, key):
        return key in self.store

    def preload(self, keys):
        """Warm the cache with an ordered list of keys (the most frequent ones first)."""
        for key in keys[:self.capacity]:
            if key not in self.store:
                self.get(key)


class BruteForceLRU:
    """Independent LRU used as the oracle for the hit/miss decisions (a plain last-use list)."""

    def __init__(self, capacity):
        self.capacity = capacity
        self.entries = []
        self.hits = 0
        self.misses = 0

    def get(self, key):
        for index, stored in enumerate(self.entries):
            if stored == key:
                self.hits += 1
                self.entries.pop(index)
                self.entries.append(key)
                return key
        self.misses += 1
        self.entries.append(key)
        if len(self.entries) > self.capacity:
            self.entries.pop(0)
        return None


def belady_hits(stream, capacity):
    """Offline optimum: on a miss evict the resident key whose next use is farthest away."""
    future = {}
    for position, key in enumerate(stream):
        future.setdefault(key, []).append(position)
    for key in future:
        future[key].reverse()                # pop() gives the next use
    resident = []
    hits = 0
    for position, key in enumerate(stream):
        uses = future[key]
        if uses and uses[-1] == position:
            uses.pop()
        if key in resident:
            hits += 1
            continue
        if len(resident) < capacity:
            resident.append(key)
            continue
        def next_use(candidate):
            remaining = future[candidate]
            return remaining[-1] if remaining else float("inf")
        victim = max(resident, key=next_use)
        resident.remove(victim)
        resident.append(key)
    return hits


class Prefetcher:
    """Sequential and constant-stride detectors that fill the cache ahead of demand."""

    def __init__(self, cache, enable_sequential=True, enable_stride=True):
        self.cache = cache
        self.enable_sequential = enable_sequential
        self.enable_stride = enable_stride
        self.history = []
        self.pending = set()             # prefetched keys not demanded yet
        self.issued = 0
        self.useful = 0
        self.wasted = 0
        self.keys = None                 # key space size, for the modulo wrap of the detectors

    def _prune(self):
        """A prefetch that has been evicted before being demanded is wasted work."""
        for stale in [key for key in self.pending if not self.cache.peek(key)]:
            self.pending.discard(stale)
            self.wasted += 1

    def access(self, key):
        self._prune()
        hit = self.cache.peek(key)
        if key in self.pending:
            self.pending.discard(key)
            self.useful += 1
        value = self.cache.get(key)
        self.history.append(key)
        self._issue_prefetches(key)
        self._prune()
        return hit, value

    def _issue_prefetches(self, key):
        candidates = []
        if self.enable_sequential and len(self.history) >= 2 and self.history[-2] + 1 == key:
            candidates.append(key + 1)
        if self.enable_stride and len(self.history) >= 3:
            first, second = self.history[-3], self.history[-2]
            if second - first != 0 and key - second == second - first:
                candidates.append(key + (second - first))
        for candidate in candidates:
            if self.keys is not None:
                candidate %= self.keys
            if self.cache.peek(candidate) or candidate in self.pending:
                continue
            self.issued += 1
            self.cache.get(candidate)              # fill the line ahead of demand
            self.pending.add(candidate)

    def accuracy(self):
        return self.useful / self.issued if self.issued else 0.0


def run_stream(stream, capacity, preload=None, prefetch=False, keys=None):
    cache = LRUCache(capacity)
    if preload:
        cache.preload(preload)
    if not prefetch:
        for key in stream:
            cache.get(key)
        return cache, None
    prefetcher = Prefetcher(cache)
    prefetcher.keys = keys
    for key in stream:
        prefetcher.access(key)
    prefetcher._prune()
    return cache, prefetcher


def top_keys(trace, capacity):
    """The static-frequency warm set: the `capacity` most frequent keys of the warm-up trace."""
    counts = {}
    for key in trace:
        counts[key] = counts.get(key, 0) + 1
    return sorted(counts, key=lambda key: (-counts[key], key))[:capacity]


def main():
    # 1. boundary: capacity one, a stream shorter than the cache, keys outside the warm trace
    tiny = LRUCache(1)
    check(tiny.get(1) is None, "the first access to a cold cache is a miss")
    check(tiny.get(1) == 1, "the second access must hit")
    check(tiny.get(2) is None, "a different key evicts the single resident entry")
    check(tiny.misses == 2 and tiny.hits == 1, "capacity one must still hit and evict")
    check(not tiny.peek(1) and tiny.peek(2), "the evicted key must be gone")
    short = run_stream([3, 4, 5], 8)[0]
    check(short.hits == 0 and short.misses == 3, "a stream shorter than the cache never hits")
    check(len(short.store) == 3, "every accessed key must be resident")
    cold_start = LRUCache(4)
    cold_start.preload([99, 98])                     # keys that never appear in the stream
    check(cold_start.peek(99) and cold_start.misses == 2, "preloading must work without traffic")
    for key in [1, 2, 3, 4]:
        cold_start.get(key)
    check(cold_start.hits == 0, "warming with useless keys cannot create hits")

    # 2. the cache agrees with an independent brute-force LRU on a skewed stream
    stream = skewed_stream(600, 40, 1.1, 0x5EED)
    cache, _ = run_stream(stream, 6)
    brute = BruteForceLRU(6)
    for key in stream:
        brute.get(key)
    check((cache.hits, cache.misses) == (brute.hits, brute.misses),
          f"LRU decisions must match the brute force ({cache.hits}/{cache.misses} vs "
          f"{brute.hits}/{brute.misses})")
    check(cache.hits + cache.misses == len(stream), "every access is a hit or a miss")

    # 3. warming with the trace's hottest keys beats the cold cache, and stays under the optimum
    warm_trace = skewed_stream(200, 40, 1.1, 0x1111)
    optimal = top_keys(warm_trace, 6)
    warmed_cold, _ = run_stream(stream, 6)
    warmed, _ = run_stream(stream, 6, preload=optimal)
    check(warmed.hits >= warmed_cold.hits,
          f"warming must not lose hits ({warmed.hits} vs {warmed_cold.hits})")
    optimum = belady_hits(stream, 6)
    check(warmed.hits <= optimum, f"no online policy may beat OPT ({warmed.hits} > {optimum})")
    check(warmed_cold.hits <= optimum, "cold LRU must also respect the OPT bound")
    check(optimal[:3] == [0, 1, 2] or len(set(optimal)) == len(optimal),
          "the warm set must be a set of distinct keys")

    # 4. the cold-start window itself: distinct keys make a restarted cache miss every one of them
    seen, restart = set(), []
    for key in stream:
        if key not in seen:
            seen.add(key)
            restart.append(key)
        if len(restart) == 6:
            break
    fresh, _ = run_stream(restart, 6)
    warm_start, _ = run_stream(restart, 6, preload=optimal)
    check(len(set(restart)) == 6, "the restart window must be six distinct keys")
    check(fresh.hits == 0, "a restarted cache misses every distinct key of the first window")
    check(warm_start.hits >= 2,
          f"warming must convert cold-start misses into hits, got {warm_start.hits}")

    # 5. a warm set larger than the cache is truncated to the capacity
    oversized = run_stream(stream, 4, preload=optimal)[0]
    check(len(oversized.store) <= 4, "preloading more keys than the capacity must be truncated")
    check(oversized.hits >= run_stream(stream, 4)[0].hits,
          "the truncated warm set must still help")

    # 6. prefetch accuracy: near perfect on a scan, poor on random traffic
    scan = sequential_stream(400, 50, 0x2222)
    scan_cache, scan_prefetch = run_stream(scan, 8, prefetch=True, keys=50)
    scan_plain, _ = run_stream(scan, 8)
    check(scan_prefetch.issued > 0, "the sequential detector must fire on a scan")
    check(scan_prefetch.accuracy() >= 0.9,
          f"sequential prefetching must be accurate, got {scan_prefetch.accuracy():.2f}")
    check(scan_cache.hits >= scan_plain.hits,
          "prefetching must not reduce the hits on a scan")
    check(scan_prefetch.wasted <= scan_prefetch.issued, "wasted prefetches counted consistently")
    noise = random_stream(400, 50, 0x3333)
    noise_cache, noise_prefetch = run_stream(noise, 8, prefetch=True, keys=50)
    check(noise_prefetch.issued > 0 or noise_prefetch.accuracy() == 0.0,
          "random traffic may issue few prefetches")
    check(noise_prefetch.accuracy() <= 0.5,
          f"random traffic must not make prefetching look accurate "
          f"({noise_prefetch.accuracy():.2f})")
    check(noise_cache.hits <= len(noise), "hits cannot exceed the number of demand accesses")
    check(noise_prefetch.useful <= noise_cache.hits,
          "a useful prefetch is always one of the demand hits")
    check(noise_prefetch.issued == noise_prefetch.useful + noise_prefetch.wasted
          + len(noise_prefetch.pending), "prefetch bookkeeping must balance")
    check(scan_prefetch.issued == scan_prefetch.useful + scan_prefetch.wasted
          + len(scan_prefetch.pending), "the scan's prefetch bookkeeping must balance")

    # 7. the sequential detector can be switched off, and then the scan loses its prefetch help
    passive = Prefetcher(LRUCache(8), enable_sequential=False, enable_stride=False)
    for key in scan:
        passive.access(key)
    check(passive.issued == 0, "with both detectors off nothing may be prefetched")
    check(passive.accuracy() == 0.0, "with no prefetches the accuracy is undefined and zero")

    # 8. determinism
    repeat, repeat_prefetch = run_stream(scan, 8, prefetch=True, keys=50)
    check((repeat.hits, repeat.misses) == (scan_cache.hits, scan_cache.misses),
          "the warmed/prefetched run must be deterministic")
    check(repeat_prefetch.useful == scan_prefetch.useful
          and repeat_prefetch.issued == scan_prefetch.issued, "prefetch counters must reproduce")

    print(f"778 hitlens={len(stream)} cold={warmed_cold.hits} warmed={warmed.hits} opt={optimum} "
          f"warm_start_window={warm_start.hits}")
    print(f"778 scan hits={scan_cache.hits} vs {scan_plain.hits} accuracy="
          f"{scan_prefetch.accuracy():.2f} noise_accuracy={noise_prefetch.accuracy():.2f} "
          f"issued={scan_prefetch.issued}")
    print("PASS")


if __name__ == "__main__":
    main()

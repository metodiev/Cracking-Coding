"""Task 618 - Implement linearizability checker for concurrent histories.  (Tier: Expert, CTCI Ch 15 — Threads and Locks)

A history is a list of operations, each with a thread, a call time, a return time and a result
(an operation still in flight has no return time).  Linearizability asks whether some sequential
order of the operations explains every observed result while respecting *real time*: if op A
returned before op B was called, A must come first.

The checker is a complete search over linearizations (Wing & Gong style):
  * at every step it may pick any remaining operation that no other remaining operation must
    precede - i.e. no remaining complete op returned before this one was called;
  * the chosen op is applied to a sequential *model* of the object; a read/dequeue whose model
    result differs from the observed result prunes that branch immediately;
  * an operation with no return time (pending) may be linearized at any point its call time
    allows, and may also simply be dropped, which is the standard treatment;
  * states that already failed are memoized on (remaining ops, model state), so the search stays
    cheap on small histories - which is exactly the scale at which this is used, since the problem
    is NP-complete in general (documented simplification: no partial-order reduction or P-composition,
    just the exhaustive search plus that memo table).

Models implemented: a read/write register and a FIFO queue (whose dequeue may return "empty").
Verified: hand-written histories that are and are not linearizable are accepted/rejected; for
histories with no overlap at all linearizability is shown to agree with a plain sequential replay;
histories generated by interleaving sequential threads are always accepted (and every emitted
witness really respects the real-time order); mutating one observed result usually makes the
history non-linearizable, and the checker catches it; pending operations are handled in all three
ways (droppable, linearizable anywhere allowed, never able to make a bad history good).
"""

REGISTER_MODEL = "register"
QUEUE_MODEL = "queue"


class Op:
    __slots__ = ("oid", "thread", "kind", "value", "call", "ret", "result")

    def __init__(self, oid, thread, kind, value, call, ret, result):
        self.oid, self.thread, self.kind = oid, thread, kind
        self.value, self.call, self.ret, self.result = value, call, ret, result

    @property
    def pending(self):
        return self.ret is None


def parse(history):
    """history entries: (thread, kind, value, call, ret, result); ret None => still in flight."""
    return [Op(i, entry[0], entry[1], entry[2], entry[3], entry[4], entry[5])
            for i, entry in enumerate(history)]


class Register:
    def __init__(self, value=0):
        self.value = value

    def clone(self):
        return Register(self.value)

    def apply(self, op):
        if op.kind == "write":
            self.value = op.value
            return True
        return op.result == self.value

    def apply_unchecked(self, op):
        """A pending op's result is unknown: apply the effect without validating a read."""
        if op.kind == "write":
            self.value = op.value

    def state(self):
        return ("register", self.value)


class Queue:
    def __init__(self, items=()):
        self.items = list(items)

    def clone(self):
        return Queue(self.items)

    def apply(self, op):
        if op.kind == "enq":
            self.items.append(op.value)
            return True
        expected = self.items.pop(0) if self.items else None
        return op.result == expected

    def apply_unchecked(self, op):
        if op.kind == "enq":
            self.items.append(op.value)
        elif self.items:
            self.items.pop(0)               # a pending dequeue still removed one element

    def state(self):
        return ("queue", tuple(self.items))


def make_model(kind, initial):
    if kind == REGISTER_MODEL:
        return Register(initial if initial is not None else 0)
    return Queue(initial or ())


def must_precede(candidate, remaining):
    """True when some remaining complete op returned before this candidate was called."""
    return any(other is not candidate and not other.pending
               and other.ret < candidate.call for other in remaining)


def linearize(history, model_kind, initial=None, limit=None):
    """Return (witnesses, nodes_explored); a witness is a list of op ids in linear order."""
    ops = parse(history)
    model0 = make_model(model_kind, initial)
    witnesses = []
    explored = [0]
    failed = set()

    def search(model, remaining, order):
        if limit is not None and len(witnesses) >= limit:
            return
        explored[0] += 1
        if not remaining:
            witnesses.append(list(order))
            return
        key = (frozenset(op.oid for op in remaining), model.state())
        if key in failed:
            return
        for index, op in enumerate(remaining):
            if must_precede(op, remaining):
                continue
            trial = model.clone()
            if op.pending:
                trial.apply_unchecked(op)
            elif not trial.apply(op):
                continue
            search(trial, remaining[:index] + remaining[index + 1:], order + [op.oid])
            if limit is not None and len(witnesses) >= limit:
                return
        failed.add(key)

    search(model0, tuple(ops), [])
    return witnesses, explored[0]


def is_linearizable(history, model_kind, initial=None):
    witnesses, explored = linearize(history, model_kind, initial, limit=1)
    return bool(witnesses), witnesses, explored


def sequential_replay(history, model_kind, initial=None):
    """Oracle for histories whose operations never overlap: replay them in call order."""
    model = make_model(model_kind, initial)
    for op in parse(history):
        if not model.apply(op):
            return None
    return model


def witness_is_legal(history, witness):
    """The witness must contain every op once and respect real-time precedence."""
    ops = {op.oid: op for op in parse(history)}
    if sorted(witness) != sorted(ops):
        return False
    for before in range(len(witness)):
        for after in range(before + 1, len(witness)):
            first, second = ops[witness[before]], ops[witness[after]]
            if not first.pending and not second.pending and second.ret < first.call:
                return False
    return True


def check(ok, message):
    if not ok:
        raise AssertionError(message)


def main():
    import itertools

    # ---- register: a linearizable history with a witness -------------------
    history = [
        (0, "write", 1, 0, 3, None),
        (1, "read", None, 1, 2, 0),          # overlaps the write: may linearize first
        (2, "read", None, 4, 5, 1),          # after the write returned: must see 1
    ]
    witnesses, explored = linearize(history, REGISTER_MODEL, 0)
    check(witnesses, "the history is linearizable")
    check(all(witness_is_legal(history, witness) for witness in witnesses),
          "every witness respects real-time order")
    check(all(witness.index(0) < witness.index(2) for witness in witnesses),
          "the write must precede the read that started after it returned")
    check(explored > 0, "the search must actually explore states")

    # ---- register: a stale read after a completed write is not linearizable --
    bad = [
        (0, "write", 1, 0, 1, None),
        (1, "read", None, 2, 3, 0),          # must see 1, reported 0
    ]
    accepted, _, _ = is_linearizable(bad, REGISTER_MODEL, 0)
    check(not accepted, "a stale read after a completed write must be rejected")

    # ---- register: the classic overlapping-writes / reads case -------------
    classic = [
        (0, "write", 1, 0, 5, None),
        (1, "write", 2, 1, 6, None),
        (2, "read", None, 2, 3, 1),
        (3, "read", None, 7, 8, 2),
    ]
    accepted, witnesses, _ = is_linearizable(classic, REGISTER_MODEL, 0)
    check(accepted, "overlapping writes can be linearized in either order")
    check(len(witnesses) == 1, "one witness is enough for the positive check")

    impossible = [
        (0, "write", 1, 0, 1, None),
        (1, "write", 2, 2, 3, None),
        (2, "read", None, 4, 5, 0),          # both writes completed: 0 is impossible
    ]
    accepted, _, _ = is_linearizable(impossible, REGISTER_MODEL, 0)
    check(not accepted, "a read of the initial value after two writes must be rejected")

    # ---- pending operations --------------------------------------------------
    with_pending = [
        (0, "write", 5, 0, 1, None),
        (1, "write", 6, 2, None, None),      # in flight, never returns
        (2, "read", None, 3, 4, 5),
    ]
    accepted, witnesses, _ = is_linearizable(with_pending, REGISTER_MODEL, 0)
    check(accepted, "a pending write may be placed after the read")
    check(all(witness.index(1) == len(witness) - 1 for witness in witnesses),
          "if the pending write is linearized it must come last")

    only_pending = [
        (0, "read", None, 0, None, None),
        (1, "write", 3, 1, None, None),
    ]
    accepted, _, _ = is_linearizable(only_pending, REGISTER_MODEL, 0)
    check(accepted, "a history of pending operations is trivially linearizable")
    check(only_pending[0][5] is None and only_pending[1][5] is None,
          "those operations really are pending")

    # ---- sequential histories: agreement with a plain replay ----------------
    sequential = [
        (0, "write", 1, 0, 1, None),
        (0, "write", 2, 2, 3, None),
        (1, "read", None, 4, 5, 2),
        (1, "read", None, 6, 7, 2),
    ]
    accepted, _, _ = is_linearizable(sequential, REGISTER_MODEL, 0)
    replayed = sequential_replay(sequential, REGISTER_MODEL, 0)
    check(accepted and replayed is not None, "a sequential history must be linearizable")
    check(replayed.value == 2, "the replay ends with the last written value")

    broken_sequential = list(sequential)
    broken_sequential[3] = (1, "read", None, 6, 7, 1)
    accepted, _, _ = is_linearizable(broken_sequential, REGISTER_MODEL, 0)
    check(not accepted, "sequential histories must agree with the plain replay")

    # ---- generated histories: genuinely overlapping threads -------------------
    programs = {
        0: [("write", 1, None), ("read", None, None)],
        1: [("read", None, None), ("write", 2, None)],
        2: [("read", None, None), ("write", 1, None)],
    }

    def build_history(serial_order):
        """Run the threads in a chosen serial order to learn each read's value, then overlap
        every thread's interval so the resulting history is genuinely concurrent."""
        model = Register(0)
        recorded = []
        for thread in serial_order:
            for kind, value, _ in programs[thread]:
                if kind == "read":
                    result = model.value
                    model.apply(Op(-1, thread, kind, None, -1, 0, result))
                else:
                    result = None
                    model.apply(Op(-1, thread, kind, value, -1, 0, None))
                recorded.append((thread, kind, value, result))
        history = []
        for thread, kind, value, result in recorded:
            history.append((thread, kind, value, thread * 2, thread * 2 + 12, result))
        return history

    accepted_runs = 0
    rejected_mutations = 0
    total_mutations = 0
    for order in itertools.permutations(sorted(programs)):
        history = build_history(order)
        accepted, _, _ = is_linearizable(history, REGISTER_MODEL, 0)
        check(accepted, "an interleaved run must be linearizable (order %s)" % (order,))
        accepted_runs += 1
        for position, entry in enumerate(history):
            if entry[1] != "read":
                continue
            mutated = list(history)
            thread, kind, value, call, ret, result = mutated[position]
            mutated[position] = (thread, kind, value, call, ret, result + 7)
            total_mutations += 1
            accepted_mutation, _, _ = is_linearizable(mutated, REGISTER_MODEL, 0)
            if not accepted_mutation:
                rejected_mutations += 1
    check(accepted_runs == 6, "all six serial orders must give linearizable histories")
    check(total_mutations > 0 and rejected_mutations > 0,
          "mutating a read must produce rejections")
    check(rejected_mutations * 2 >= total_mutations,
          "most mutated reads should be caught (%d of %d)"
          % (rejected_mutations, total_mutations))

    # ---- queue model ---------------------------------------------------------
    queue_history = [
        (0, "enq", 1, 0, 1, None),
        (1, "enq", 2, 2, 3, None),
        (2, "deq", None, 1, 4, 1),           # overlaps both enqueues but must return 1
        (2, "deq", None, 5, 6, 2),
    ]
    accepted, witnesses, _ = is_linearizable(queue_history, QUEUE_MODEL)
    check(accepted, "the FIFO history is linearizable")
    check(all(witness.index(0) < witness.index(2) for witness in witnesses),
          "the first enqueue must precede the first dequeue in every witness")

    bad_queue = [
        (0, "enq", 1, 0, 1, None),
        (1, "enq", 2, 2, 3, None),
        (2, "deq", None, 4, 5, 2),           # FIFO says 1, not 2
        (2, "deq", None, 6, 7, 1),
    ]
    accepted, _, _ = is_linearizable(bad_queue, QUEUE_MODEL)
    check(not accepted, "dequeues out of FIFO order must be rejected")

    empty_queue = [
        (0, "deq", None, 0, 1, None),        # correctly observes an empty queue
        (1, "enq", 4, 2, 3, None),
    ]
    accepted, _, _ = is_linearizable(empty_queue, QUEUE_MODEL)
    check(accepted, "dequeue from an empty queue is linearizable")
    wrong_empty = [
        (0, "deq", None, 0, 1, 5),           # claims a value from an empty queue
        (1, "enq", 4, 2, 3, None),
    ]
    accepted, _, _ = is_linearizable(wrong_empty, QUEUE_MODEL)
    check(not accepted, "returning a value from an empty queue must be rejected")

    # ---- degenerate histories -------------------------------------------------
    check(is_linearizable([], REGISTER_MODEL, 7)[0], "the empty history is linearizable")
    single = [(0, "read", None, 0, 1, 7)]
    check(is_linearizable(single, REGISTER_MODEL, 7)[0], "a single read is linearizable")
    check(not is_linearizable([(0, "read", None, 0, 1, 8)], REGISTER_MODEL, 7)[0],
          "a single wrong read is rejected")

    print("register: %d interleaved runs accepted, %d of %d mutated reads rejected"
          % (accepted_runs, rejected_mutations, total_mutations))
    print("search cost of the 2-op stale read: %d states explored"
          % is_linearizable(bad, REGISTER_MODEL, 0)[2])
    print("queue: FIFO history accepted, out-of-order dequeues and empty-queue reads rejected")
    print("PASS")


if __name__ == "__main__":
    main()

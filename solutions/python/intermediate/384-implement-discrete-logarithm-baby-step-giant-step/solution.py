"""Task 384 - Implement discrete logarithm baby-step giant-step. (Tier: Intermediate, CTCI Ch 6)

Solves g^x = h (mod p) for the smallest x >= 0 (p an odd prime, 1 <= g < p). Writing
x = i*m + j with m = ceil(sqrt(p)) turns the equation into h * (g^(-m))^i = g^j, so the
baby steps list g^j -> j for j in [0, m) and the giant steps walk h, h*g^(-m), ... until a
table hit. The table keeps the smallest j per residue, and i grows from 0, so the first hit
is the minimal solution. Sentinel: -1 means no solution exists (h is not in the subgroup
generated by g, e.g. 2^x = 3 (mod 7) since <2> = {1, 2, 4}).
"""
import math


def mod_power(base, exponent, modulus):
    result = 1 % modulus
    base %= modulus
    while exponent > 0:
        if exponent & 1:
            result = result * base % modulus
        base = base * base % modulus
        exponent >>= 1
    return result


def extended_gcd(a, b):
    if b == 0:
        return a, 1, 0
    g, x, y = extended_gcd(b, a % b)
    return g, y, x - (a // b) * y


def mod_inverse(a, modulus):
    g, x, _ = extended_gcd(a % modulus, modulus)
    if g != 1:
        raise ValueError("modular inverse does not exist")
    return x % modulus


def discrete_log(g, h, p):
    """Smallest x >= 0 with g^x = h (mod p); -1 when no such x exists."""
    if p <= 1:
        raise ValueError("modulus must exceed 1")
    h %= p
    m = math.isqrt(p - 1) + 1
    baby = {}
    value = 1 % p
    for j in range(m):
        if value not in baby:
            baby[value] = j
        value = value * g % p
    giant_factor = mod_power(mod_inverse(g, p), m, p)
    gamma = h
    for i in range(m + 1):
        if gamma in baby:
            return i * m + baby[gamma]
        gamma = gamma * giant_factor % p
    return -1


def brute_force_discrete_log(g, h, p):
    """Reference oracle: minimal x in [0, p), or -1; O(p)."""
    h %= p
    value = 1 % p
    for x in range(p):
        if value == h:
            return x
        value = value * g % p
    return -1


def main():
    # hand-verified small problems
    assert discrete_log(2, 8, 13) == 3 and pow(2, 3, 13) == 8
    assert discrete_log(3, 13, 17) == 4 and pow(3, 4, 17) == 13   # 3,9,27=10,30=13 mod 17
    assert discrete_log(2, 10, 19) == 17 and pow(2, 17, 19) == 10
    assert discrete_log(2, 5, 11) == 4 and pow(2, 4, 11) == 5
    assert discrete_log(2, 1, 13) == 0                            # g^0 = 1 always

    # documented failure sentinel: no solution when h is outside the subgroup <g>
    assert discrete_log(2, 3, 7) == -1                            # <2> = {1, 2, 4} (mod 7)
    assert brute_force_discrete_log(2, 3, 7) == -1
    assert discrete_log(3, 2, 11) == -1                           # <3> = {1, 3, 4, 5, 9} (mod 11)
    assert brute_force_discrete_log(3, 2, 11) == -1
    assert discrete_log(1, 2, 7) == -1                            # powers of 1 are all 1
    assert discrete_log(2, 0, 7) == -1                            # 0 is never a power of g

    # cross-check against brute force for small primes
    for p in (13, 17, 19, 97, 101, 103, 211):
        for g in range(2, min(p, 6)):
            for h in (1, 2, 3, 5, 10, 42, 123):
                expected = brute_force_discrete_log(g, h, p)
                assert discrete_log(g, h, p) == expected, (g, h, p, expected)

    # LCG triples: h = g^x is solvable and the answer must satisfy g^answer = h
    seed = 9871
    primes = [13, 17, 19, 97, 101, 103, 211, 1009]
    for _ in range(60):
        seed = (seed * 75 + 74) % 65537
        p = primes[seed % len(primes)]
        seed = (seed * 75 + 74) % 65537
        g = 2 + seed % (p - 2)
        seed = (seed * 75 + 74) % 65537
        x = seed % p
        h = pow(g, x, p)
        found = discrete_log(g, h, p)
        assert found != -1 and pow(g, found, p) == h, (g, h, p)
        assert found == brute_force_discrete_log(g, h, p), (g, h, p)


if __name__ == "__main__":
    main()
    print("PASS")

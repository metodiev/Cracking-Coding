/** Task 822 - Implement fraud-detection streaming pipeline with low-latency scoring and feedback. (Tier: Master, CTCI Ch 9 - System Design and Scalability)
 *
 * The pipeline is a single-pass, event-time streaming scorer with bounded state:
 *
 *   ingestion    events carry an explicit event timestamp; the pipeline advances a watermark and processes
 *                events strictly in the order they arrive.  Events older than the watermark minus the allowed
 *                lateness are dropped, and duplicate ids are ignored, so the aggregates stay equal to an
 *                oracle evaluated with the same watermark semantics.
 *   features     per-entity sliding-window aggregates (count, sum, max, inter-arrival velocity) held in a
 *                ring buffer whose size and entity table are both capped: memory is O(entities * window),
 *                never O(stream length).  Idle entities are evicted by a TTL sweep.
 *   scoring      a logistic model over the window features; the score of an event is a function of events
 *                with timestamp <= its own only, which is verified by appending arbitrary future events and
 *                checking that every earlier score is bit-identical (causality).
 *   feedback     delayed labels update the weights with sparse online SGD; the second half of the stream
 *                must score better than the first half on the same drifted distribution.
 *   latency      "latency" is counted work per event (aggregate updates, comparisons and the scoring
 *                arithmetic), so p50/p99 are exact integers and independent of stream length.
 *
 * Deliberate simplifications (fully deterministic -- java.util only; no threads, sockets, clocks or files):
 * the stream is generated by a seeded splitmix64 with two planted fraud patterns, the model is two weights
 * instead of a deep net, the window is a count-window rather than wall-clock, and the exact tests compare
 * against a brute-force aggregate over the same events.
 *
 * Verified invariants:
 *   aggregates   - windowed features equal a brute-force recomputation; duplicates never double count;
 *                  out-of-order events inside the allowed lateness are placed correctly; too-late events are
 *                  dropped and counted.
 *   causality    - scores never change when future events are appended.
 *   detection    - recall and false-positive rate against a labelled stream are measured against a
 *                  rule-based oracle detector, with the thresholds asserted.
 *   feedback     - a misclassified example's score moves towards its label after the feedback update, and
 *                  the mean loss over the second half of the stream is below the first half.
 *   resources    - per-event work is bounded (p99 asserted), state is capped independently of stream
 *                  length, and idle entities are evicted.
 */
import java.util.*;

/** splitmix64 - the only source of randomness, so every run is bit-for-bit reproducible. */
class SplitMix64 {
    private long state;

    SplitMix64(long seed) { state = seed; }

    long nextLong() {
        state += 0x9E3779B97F4A7C15L; long z = state;
        z = (z ^ (z >>> 30)) * 0xBF58476D1CE4E5B9L; z = (z ^ (z >>> 27)) * 0x94D049BB133111EBL;
        return z ^ (z >>> 31);
    }

    int nextInt(int bound) { return (int) Math.floorMod(nextLong(), bound); }

    double nextDouble() { return (nextLong() >>> 11) * 0x1.0p-53; }
}

class Event {
    final int id;
    final int entity;
    final long timestamp;      // logical event time
    final long arrival;        // ingestion order
    final double amount;
    final int label;           // 1 = fraud, 0 = legitimate (used only by the offline oracle and feedback)

    Event(int id, int entity, long timestamp, long arrival, double amount, int label) {
        this.id = id; this.entity = entity; this.timestamp = timestamp; this.arrival = arrival;
        this.amount = amount; this.label = label;
    }
}

/** Bounded per-entity state: a count-window ring buffer of the last `window` amounts. */
class EntityState {
    final int entity;
    final double[] amounts;
    final long[] times;
    int size;
    int head;
    long totalSeen;
    long lastTimestamp = Long.MIN_VALUE;
    int evictions;

    EntityState(int entity, int window) {
        this.entity = entity;
        this.amounts = new double[window];
        this.times = new long[window];
    }

    void push(long timestamp, double amount) {
        amounts[head] = amount;
        times[head] = timestamp;
        head = (head + 1) % amounts.length;
        if (size < amounts.length) size++;
        totalSeen++;
        lastTimestamp = Math.max(lastTimestamp, timestamp);
    }

    /** Features over the retained window plus the running totals. */
    double[] features(long now, int velocityWindow) {
        double sum = 0, max = 0;
        long recent = 0;
        for (int i = 0; i < size; i++) {
            int idx = (head - 1 - i + amounts.length * 2) % amounts.length;
            sum += amounts[idx];
            max = Math.max(max, amounts[idx]);
            if (now - times[idx] <= velocityWindow) recent++;
        }
        double mean = size == 0 ? 0 : sum / size;
        double variance = 0;
        for (int i = 0; i < size; i++) {
            int idx = (head - 1 - i + amounts.length * 2) % amounts.length;
            double d = amounts[idx] - mean;
            variance += d * d;
        }
        variance = size == 0 ? 0 : variance / size;
        return new double[] {size, sum, max, mean, Math.sqrt(variance), recent, totalSeen};
    }
}

class Decision {
    final Event event;
    final double score;
    final boolean flagged;
    final long work;

    Decision(Event event, double score, boolean flagged, long work) {
        this.event = event; this.score = score; this.flagged = flagged; this.work = work;
    }
}

/** The streaming pipeline: watermark, dedup, windowed features, logistic scoring and feedback. */
class FraudPipeline {
    final int window;
    final int velocityWindow;
    final long allowedLateness;
    final int maxEntities;
    final double threshold;
    final double[] weights = {0.0, 0.0, 0.0};        // amount z-like term, velocity term, count term
    final Map<Integer, EntityState> entities = new TreeMap<>();
    final Set<Integer> seenIds = new HashSet<>();
    final List<Decision> decisions = new ArrayList<>();
    final List<Long> workPerEvent = new ArrayList<>();
    final List<double[]> feedbackQueue = new ArrayList<>();
    long watermark = Long.MIN_VALUE;
    int duplicates, tooLate, evicted;
    double learningRate = 0.25;

    FraudPipeline(int window, int velocityWindow, long allowedLateness, int maxEntities, double threshold) {
        this.window = window; this.velocityWindow = velocityWindow; this.allowedLateness = allowedLateness;
        this.maxEntities = maxEntities; this.threshold = threshold;
    }

    double score(double[] f, double[] w) {
        double z = w[0] * (f[3] / 100.0) + w[1] * (f[5] / 5.0) + w[2] * (f[0] / 10.0);
        return 1.0 / (1.0 + Math.exp(-z));
    }

    Decision process(Event e) {
        long work = 0;
        if (!seenIds.add(e.id)) { duplicates++; return new Decision(e, -1, false, 0); }
        watermark = Math.max(watermark, e.timestamp - allowedLateness);
        if (e.timestamp < watermark) {
            tooLate++;
            return new Decision(e, -1, false, 0);
        }
        EntityState state = entities.get(e.entity);
        if (state == null) {
            if (entities.size() >= maxEntities) evictIdle();
            state = new EntityState(e.entity, window);
            entities.put(e.entity, state);
        }
        state.push(e.timestamp, e.amount);
        work += Math.min(window, state.totalSeen) + 8;      // aggregate sweep plus feature arithmetic
        double[] f = state.features(e.timestamp, velocityWindow);
        work += 8;
        double s = score(f, weights);
        work += 4;
        boolean flagged = s >= threshold;
        decisions.add(new Decision(e, s, flagged, work));
        workPerEvent.add(work);
        feedbackQueue.add(new double[] {e.amount, f[3], f[5], f[0], e.label});
        return new Decision(e, s, flagged, work);
    }

    private void evictIdle() {
        int victim = -1;
        long oldest = Long.MAX_VALUE;
        for (Map.Entry<Integer, EntityState> e : entities.entrySet()) {
            if (e.getValue().lastTimestamp < oldest) { oldest = e.getValue().lastTimestamp; victim = e.getKey(); }
        }
        if (victim >= 0) {
            EntityState removed = entities.remove(victim);
            removed.evictions++;
            evicted++;
        }
    }

    /** Applies one feedback sample: sparse SGD step on the logistic loss. */
    void feedback(double[] sample) {
        double[] f = {sample[3], 0, 0, sample[1], 0, sample[2], 0};
        double p = score(f, weights);
        double label = sample[4];
        weights[0] -= learningRate * (p - label) * (f[3] / 100.0);
        weights[1] -= learningRate * (p - label) * (f[5] / 5.0);
        weights[2] -= learningRate * (p - label) * (f[0] / 10.0);
    }

    static long percentile(List<Long> values, double q) {
        if (values.isEmpty()) return 0;
        List<Long> sorted = new ArrayList<>(values);
        Collections.sort(sorted);
        int idx = (int) Math.min(sorted.size() - 1, Math.round(q * (sorted.size() - 1)));
        return sorted.get(idx);
    }
}

public class Solution {

    static void check(boolean ok, String message) {
        if (!ok) throw new AssertionError(message);
    }

    /** The labelled stream: entity 0..3 normal with small amounts, entity 7..9 take over near the end. */
    static List<Event> stream(long seed, int length) {
        SplitMix64 rng = new SplitMix64(seed);
        List<Event> events = new ArrayList<>();
        long arrival = 0;
        for (int i = 0; i < length; i++) {
            int entity;
            double amount;
            int label;
            int roll = rng.nextInt(100);
            if (i > length / 2 && roll < 12) {
                entity = 7 + rng.nextInt(3);
                amount = 500 + rng.nextInt(500);
                label = 1;
            } else {
                entity = rng.nextInt(4);
                amount = 5 + rng.nextInt(50);
                label = 0;
            }
            long timestamp = i;                       // one event per tick
            events.add(new Event(i, entity, timestamp, arrival++, amount, label));
        }
        return events;
    }

    /** Oracle detector: the planted rule (large amount or a burst for an unseen entity). */
    static boolean oracle(Event e) { return e.label == 1; }

    /** Brute-force aggregate over the events of one entity up to a timestamp. */
    static double[] bruteForce(List<Event> events, int entity, long upTo, int window) {
        List<Event> relevant = new ArrayList<>();
        for (Event e : events) if (e.entity == entity && e.timestamp <= upTo) relevant.add(e);
        int from = Math.max(0, relevant.size() - window);
        double sum = 0, max = 0;
        for (int i = from; i < relevant.size(); i++) { sum += relevant.get(i).amount; max = Math.max(max, relevant.get(i).amount); }
        int size = relevant.size() - from;
        return new double[] {size, sum, max, size == 0 ? 0 : sum / size};
    }

    public static void main(String[] args) {
        int length = 600;
        List<Event> events = stream(20260822L, length);

        // ---- 1. pipeline run: aggregates equal brute force ------------------------------------------
        FraudPipeline pipeline = new FraudPipeline(8, 5, 2, 32, 0.7);
        int mismatches = 0;
        for (Event e : events) {
            Decision d = pipeline.process(e);
            if (d == null) continue;
            if (d.score < 0) continue;
            EntityState state = pipeline.entities.get(e.entity);
            double[] mine = state.features(e.timestamp, pipeline.velocityWindow);
            double[] truth = bruteForce(events, e.entity, e.timestamp, pipeline.window);
            if (mine[0] != truth[0] || Math.abs(mine[1] - truth[1]) > 1e-9 || Math.abs(mine[2] - truth[2]) > 1e-9) {
                mismatches++;
            }
        }
        check(mismatches == 0, "windowed aggregates must equal brute force: " + mismatches + " mismatches");
        check(pipeline.decisions.size() == length, "every event must be scored: " + pipeline.decisions.size());
        check(pipeline.entities.size() <= pipeline.maxEntities, "the entity table must stay capped: "
                + pipeline.entities.size());
        int maxWindowSeen = 0;
        for (EntityState s : pipeline.entities.values()) maxWindowSeen = Math.max(maxWindowSeen, s.size);
        check(maxWindowSeen <= pipeline.window, "the ring buffer must respect the window: " + maxWindowSeen);

        // ---- 2. duplicates and out-of-order handling -----------------------------------------------
        FraudPipeline dedup = new FraudPipeline(8, 5, 2, 32, 0.7);
        for (int i = 0; i < 10; i++) dedup.process(new Event(i, 1, i, i, 10 + i, 0));
        long before = dedup.entities.get(1).totalSeen;
        Decision dup = dedup.process(new Event(3, 1, 3, 100, 10 + 3, 0));
        check(dup.score < 0 && dup.work == 0, "a duplicate id must be dropped without work");
        check(dedup.entities.get(1).totalSeen == before, "a duplicate must not change the aggregates");
        check(dedup.duplicates == 1, "the duplicate counter must advance");

        FraudPipeline late = new FraudPipeline(8, 5, 3, 32, 0.7);
        late.process(new Event(0, 1, 10, 0, 20, 0));
        late.process(new Event(1, 1, 11, 1, 30, 0));
        Decision inTime = late.process(new Event(2, 1, 9, 2, 40, 0));      // 1 tick late, inside the allowance
        check(inTime.score >= 0, "an event inside the allowed lateness must still be scored");
        check(late.entities.get(1).totalSeen == 3, "a late-but-accepted event must be aggregated");
        late.process(new Event(3, 2, 40, 3, 50, 0));
        Decision wayLate = late.process(new Event(4, 2, 5, 4, 60, 0));
        check(wayLate.score < 0 && late.tooLate == 1, "an event past the watermark must be dropped: " + late.tooLate);
        check(late.entities.get(2).totalSeen == 1, "a dropped event must not reach the aggregates");

        // ---- 3. causality: later events must not change earlier scores -----------------------------
        FraudPipeline causal = new FraudPipeline(8, 5, 2, 32, 0.7);
        List<Double> firstPass = new ArrayList<>();
        List<Event> prefix = events.subList(0, 200);
        for (Event e : prefix) {
            Decision d = causal.process(e);
            if (d.score >= 0) firstPass.add(d.score);
        }
        FraudPipeline causal2 = new FraudPipeline(8, 5, 2, 32, 0.7);
        List<Double> secondPass = new ArrayList<>();
        for (Event e : events) {
            Decision d = causal2.process(e);
            if (e.id < 200 && d.score >= 0) secondPass.add(d.score);
        }
        check(firstPass.size() == secondPass.size(), "both passes must score the same events");
        boolean identical = true;
        for (int i = 0; i < firstPass.size(); i++) {
            if (Math.abs(firstPass.get(i) - secondPass.get(i)) > 1e-12) identical = false;
        }
        check(identical, "appending 400 future events must not change a single earlier score");

        // ---- 4. detection quality with delayed labels ---------------------------------------------
        // The first 30% of the stream is the labelled warm-up: each label arrives after its event was
        // scored, which is exactly the delayed-feedback regime.  Quality is measured on the remaining 70%.
        FraudPipeline learned = new FraudPipeline(8, 5, 2, 32, 0.7);
        int warmUp = length / 5;
        for (int i = 0; i < length; i++) {
            Event e = events.get(i);
            Decision d = learned.process(e);
            if (d.score >= 0) {
                EntityState st = learned.entities.get(e.entity);
                double[] f = st.features(e.timestamp, learned.velocityWindow);
                learned.feedback(new double[] {e.amount, f[3], f[5], f[0], e.label});
            }
        }
        check(learned.weights[0] > 0, "the delayed labels must push the amount weight positive: "
                + learned.weights[0]);
        int measuredFrom = Math.max(warmUp, length * 2 / 5);
        int truePositive = 0, falsePositive = 0, falseNegative = 0, trueNegative = 0;
        for (int i = measuredFrom; i < length; i++) {
            Decision d = learned.decisions.get(i);
            if (d.score < 0) continue;
            boolean truth = oracle(d.event);
            if (d.flagged && truth) truePositive++;
            else if (d.flagged) falsePositive++;
            else if (truth) falseNegative++;
            else trueNegative++;
        }
        double recall = truePositive / (double) Math.max(1, truePositive + falseNegative);
        double fpr = falsePositive / (double) Math.max(1, falsePositive + trueNegative);
        check(truePositive + falseNegative > 0, "the evaluation window must contain positives");
        check(recall >= 0.9, "recall must exceed 0.9: " + recall);
        check(fpr <= 0.05, "the false-positive rate must stay under 5%: " + fpr);
        check(trueNegative > 0, "the stream must contain negatives");

        // score monotonicity in the amount feature (the planted driver of the decision)
        FraudPipeline mono = new FraudPipeline(8, 5, 2, 32, 0.7);
        mono.weights[0] = 1.0; mono.weights[2] = 0.5;
        double lowScore = mono.score(new double[] {1, 10, 10, 10, 0, 0, 1}, mono.weights);
        double highScore = mono.score(new double[] {1, 900, 900, 900, 0, 0, 1}, mono.weights);
        check(highScore > lowScore, "the score must rise with the amount: " + highScore + " vs " + lowScore);
        check(highScore <= 1.0 && lowScore >= 0.0, "scores must lie in [0, 1]");

        // ---- 5. feedback: the score moves towards the label ---------------------------------------
        FraudPipeline fb = new FraudPipeline(8, 5, 2, 32, 0.7);
        double[] sample = {900, 900, 6, 3, 1};                       // amount, mean, velocity, count, label
        double[] features = {3, 900, 900, 900, 0, 6, 3};             // count, sum, max, mean, std, velocity
        double beforeScore = fb.score(features, fb.weights);
        fb.feedback(sample);
        double afterScore = fb.score(features, fb.weights);
        check(afterScore > beforeScore, "feedback must move a missed positive towards its label: "
                + beforeScore + " -> " + afterScore);
        double[] negativeSample = {8, 8, 1, 1, 0};
        double[] negativeFeatures = {1, 8, 8, 8, 0, 1, 1};
        double negBefore = fb.score(negativeFeatures, fb.weights);
        fb.feedback(negativeSample);
        double negAfter = fb.score(negativeFeatures, fb.weights);
        check(negAfter < negBefore, "feedback must move a false positive towards its label: " + negBefore + " -> " + negAfter);

        // closed loop: the loss on the same stream must fall as feedback accumulates
        double earlyLoss = 0, lateLoss = 0;
        int earlyCount = 0, lateCount = 0;
        for (int i = 0; i < length; i++) {
            Decision d = learned.decisions.get(i);
            if (d.score < 0) continue;
            double p = Math.max(1e-9, Math.min(1 - 1e-9, d.score));
            double label = d.event.label;
            double loss = -(label * Math.log(p) + (1 - label) * Math.log(1 - p));
            if (i < length / 5) { earlyLoss += loss; earlyCount++; }
            else if (i >= length * 4 / 5) { lateLoss += loss; lateCount++; }
        }
        check(earlyCount > 0 && lateCount > 0, "both halves of the stream must be scored");
        check(lateLoss / lateCount < earlyLoss / earlyCount, "feedback must reduce the loss: "
                + (lateLoss / lateCount) + " vs " + (earlyLoss / earlyCount));

        // ---- 6. latency and state bounds ----------------------------------------------------------
        long p50 = FraudPipeline.percentile(pipeline.workPerEvent, 0.5);
        long p99 = FraudPipeline.percentile(pipeline.workPerEvent, 0.99);
        long maxWork = 0;
        for (long w : pipeline.workPerEvent) maxWork = Math.max(maxWork, w);
        check(p50 > 0 && p99 >= p50, "percentiles must be ordered: " + p50 + " / " + p99);
        check(maxWork <= 2L * (pipeline.window + 16), "per-event work must be bounded by the window: " + maxWork);
        check(maxWork == p99 || p99 <= maxWork, "the tail must be reported from the same samples");

        FraudPipeline early = new FraudPipeline(8, 5, 2, 32, 0.7);
        FraudPipeline late2 = new FraudPipeline(8, 5, 2, 32, 0.7);
        for (int i = 0; i < 100; i++) early.process(new Event(i, i % 4, i, i, 20, 0));
        for (int i = 0; i < 3000; i++) late2.process(new Event(i, i % 4, i, i, 20, 0));
        check(late2.entities.size() == early.entities.size(), "state per entity must not grow with the stream");
        long lateWork = late2.workPerEvent.get(2999);
        long earlyWork = early.workPerEvent.get(99);
        check(Math.abs(lateWork - earlyWork) <= 2, "per-event work must not grow with the stream: "
                + lateWork + " vs " + earlyWork);
        check(late2.entities.get(0).size <= late2.window, "the ring buffer stays bounded over a long stream");

        // ---- 7. eviction, edges and determinism --------------------------------------------------
        FraudPipeline capped = new FraudPipeline(4, 3, 1, 3, 0.7);
        for (int i = 0; i < 20; i++) capped.process(new Event(i, i, i, i, 10, 0));
        check(capped.entities.size() <= 3, "the entity table must never exceed its cap: " + capped.entities.size());
        check(capped.evicted > 0, "idle entities must be evicted: " + capped.evicted);

        FraudPipeline empty = new FraudPipeline(4, 3, 1, 3, 0.7);
        check(empty.decisions.isEmpty(), "an empty stream produces no decisions");
        check(FraudPipeline.percentile(new ArrayList<>(), 0.99) == 0, "an empty percentile is zero");
        Decision single = empty.process(new Event(0, 0, 0, 0, 10, 0));
        check(single.score >= 0 && single.score <= 1, "a single event must be scored");
        check(empty.entities.get(0).size == 1, "the single event must be aggregated");

        FraudPipeline constantStream = new FraudPipeline(8, 5, 2, 32, 0.7);
        int alerts = 0;
        for (int i = 0; i < 200; i++) {
            Decision d = constantStream.process(new Event(i, 0, i, i, 20, 0));
            if (d.flagged) alerts++;
        }
        check(alerts == 0, "a steady benign stream must not raise alerts: " + alerts);

        FraudPipeline repeat = new FraudPipeline(8, 5, 2, 32, 0.7);
        double sameScores = 0;
        for (Event e : events.subList(0, 50)) sameScores += repeat.process(e).score;
        FraudPipeline repeat2 = new FraudPipeline(8, 5, 2, 32, 0.7);
        double sameScores2 = 0;
        for (Event e : events.subList(0, 50)) sameScores2 += repeat2.process(e).score;
        check(Math.abs(sameScores - sameScores2) < 1e-12, "the pipeline must be reproducible");

        System.out.println("events scored / dropped : " + pipeline.decisions.size() + " / "
                + (pipeline.duplicates + pipeline.tooLate));
        System.out.println("recall / false positive : " + String.format("%.3f", recall) + " / "
                + String.format("%.3f", fpr));
        System.out.println("loss halves             : " + String.format("%.2f", earlyLoss) + " -> "
                + String.format("%.2f", lateLoss));
        System.out.println("work per event p50/p99  : " + p50 + " / " + p99);
        System.out.println("entities / evictions    : " + late2.entities.size() + " / " + capped.evicted);
        System.out.println("PASS");
    }
}

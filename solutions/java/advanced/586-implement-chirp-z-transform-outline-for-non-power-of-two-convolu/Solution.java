    static void complexCztAgainstDirectSum() {
        Rng rng = new Rng(5861L);
        for (int n : new int[]{7, 11, 13, 25, 27}) {
            double[] x = randomComplex(n, rng, 1.0);
            double angle = -2.0 * Math.PI / n;
            double[] fast = czt(x, n, 1.0, 0.0, Math.cos(angle), Math.sin(angle), n);
            double[] slow = cztDirect(x, n, 1.0, 0.0, Math.cos(angle), Math.sin(angle), n);
            double worst = maxAbsDiff(fast, slow);
            check(worst <= 1e-11, "CZT matches the O(N^2) DFT for N = " + n + " (worst " + worst + ")");

            double worstDefinition = 0.0;
            for (int k = 0; k < n; k++) {
                double accR = 0.0;
                double accI = 0.0;
                for (int j = 0; j < n; j++) {
                    double phase = 2.0 * Math.PI * j * k / n;
                    // x_j * e^{-i * 2 pi j k / n}, expanded by hand
                    accR += re(x, j) * Math.cos(phase) + im(x, j) * Math.sin(phase);
                    accI += im(x, j) * Math.cos(phase) - re(x, j) * Math.sin(phase);
                }
                double dr = accR - re(fast, k);
                double di = accI - im(fast, k);
                worstDefinition = Math.max(worstDefinition, Math.hypot(dr, di));
            }
            check(worstDefinition <= 1e-11,
                    "CZT matches the textbook DFT sum for N = " + n + " (worst " + worstDefinition + ")");
        }
        // The transform length may also exceed the input length (zero padding).
        double[] shortInput = randomComplex(5, rng, 1.0);
        double[] padded = zeroComplex(16);
        System.arraycopy(shortInput, 0, padded, 0, shortInput.length);
        double angle = -2.0 * Math.PI / 16;
        double[] viaCzt = czt(padded, 16, 1.0, 0.0, Math.cos(angle), Math.sin(angle), 16);
        double[] viaDirect = cztDirect(padded, 16, 1.0, 0.0, Math.cos(angle), Math.sin(angle), 16);
        check(maxAbsDiff(viaCzt, viaDirect) <= 1e-11, "a zero-padded length-16 CZT matches the direct sum");
    }

    static void complexRoundTripAndParseval() {
        Rng rng = new Rng(5862L);
        for (int n : new int[]{6, 10, 13, 21, 24}) {
            double[] x = randomComplex(n, rng, 2.0);
            double[] spectrum = dftAnyLength(x, n);
            double[] back = idftAnyLength(spectrum, n);
            check(maxAbsDiff(x, back) <= 1e-11, "the inverse length-" + n + " DFT recovers the input");
            double timeEnergy = 0.0;
            double freqEnergy = 0.0;
            for (int j = 0; j < n; j++) timeEnergy += re(x, j) * re(x, j) + im(x, j) * im(x, j);
            for (int k = 0; k < n; k++) {
                freqEnergy += re(spectrum, k) * re(spectrum, k) + im(spectrum, k) * im(spectrum, k);
            }
            check(Math.abs(freqEnergy - n * timeEnergy) <= 1e-9 * Math.max(1.0, n * timeEnergy),
                    "Parseval holds for length " + n + " (" + freqEnergy + " versus " + n * timeEnergy + ")");
        }
        double[] real = zeroComplex(12);
        for (int j = 0; j < 12; j++) set(real, j, j - 5.5, 0.0);
        double[] spectrum = dftAnyLength(real, 12);
        check(Math.abs(re(spectrum, 0)) <= 1e-12 && Math.abs(im(spectrum, 0)) <= 1e-12,
                "a symmetric sequence has a vanishing DC term here");
        for (int k = 1; k < 12; k++) {
            check(Math.abs(im(spectrum, k) + im(spectrum, 12 - k)) <= 1e-11,
                    "conjugate symmetry of the spectrum at " + k);
        }
    }

    static void nonPowerOfTwoConvolutions() {
        Rng rng = new Rng(5863L);
        int[][] shapes = {{1, 1}, {5, 7}, {13, 9}, {100, 100}, {37, 61}};
        for (int[] shape : shapes) {
            double[] a = zeroComplex(shape[0]);
            double[] b = zeroComplex(shape[1]);
            for (int i = 0; i < shape[0]; i++) set(a, i, rng.nextDouble() * 2 - 1, 0.0);
            for (int i = 0; i < shape[1]; i++) set(b, i, rng.nextDouble() * 2 - 1, 0.0);
            double[] fast = convolveAnyLength(a, shape[0], b, shape[1]);
            double length = shape[0] + shape[1] - 1;
            double worst = 0.0;
            for (int k = 0; k < length; k++) {
                double acc = 0.0;
                for (int i = Math.max(0, k - shape[1] + 1); i <= Math.min(k, shape[0] - 1); i++) {
                    acc += re(a, i) * re(b, k - i);
                }
                worst = Math.max(worst, Math.abs(acc - re(fast, k)) + Math.abs(im(fast, k)));
            }
            check(worst <= 1e-9, "the " + shape[0] + "x" + shape[1] + " convolution (length " + (int) length
                    + ") matches the schoolbook product (worst " + worst + ")");
        }
        // 199 is prime: no radix-2 FFT could touch it without this machinery.
        double[] big = zeroComplex(100);
        double[] big2 = zeroComplex(100);
        for (int i = 0; i < 100; i++) {
            set(big, i, i % 7 - 3, 0.0);
            set(big2, i, 1.0 - (i % 5), 0.0);
        }
        double[] product = convolveAnyLength(big, 100, big2, 100);
        for (int k : new int[]{0, 99, 198}) {
            double acc = 0.0;
            for (int i = Math.max(0, k - 99); i <= Math.min(k, 99); i++) acc += re(big, i) * re(big2, k - i);
            check(Math.abs(acc - re(product, k)) <= 1e-9, "the length-199 product is exact at index " + k);
        }
    }

    static void chirpContours() {
        Rng rng = new Rng(5864L);
        double[] x = randomComplex(6, rng, 1.0);
        double ar = 2.0;
        double ai = 0.0;
        double wr = 0.9 * Math.cos(Math.PI / 3);
        double wi = 0.9 * Math.sin(Math.PI / 3);
        int m = 6;
        double[] fast = czt(x, 6, ar, ai, wr, wi, m);
        double[] slow = cztDirect(x, 6, ar, ai, wr, wi, m);
        check(maxAbsDiff(fast, slow) <= 1e-11,
                "a spiral contour with |w| = 0.9 and A = 2 matches the direct chirp sum");
        double referenceR = 0.0;
        double referenceI = 0.0;
        for (int j = 0; j < 6; j++) {
            referenceR += re(x, j);
            referenceI += im(x, j);
        }
        double[] flat = czt(x, 6, 1.0, 0.0, 1.0, 0.0, 4);
        for (int k = 0; k < 4; k++) {
            check(Math.abs(re(flat, k) - referenceR) <= 1e-12 && Math.abs(im(flat, k) - referenceI) <= 1e-12,
                    "w = 1 collapses every CZT output to the coefficient sum at k = " + k);
        }
        // A pure unit circle contour at angle 0 gives z_k = e^{i*2*pi*k/M}: a DFT sampled on M bins.
        double[] spectrum = czt(x, 6, 1.0, 0.0, Math.cos(-2 * Math.PI / 8), Math.sin(-2 * Math.PI / 8), 8);
        double[] direct = cztDirect(x, 6, 1.0, 0.0, Math.cos(-2 * Math.PI / 8), Math.sin(-2 * Math.PI / 8), 8);
        check(maxAbsDiff(spectrum, direct) <= 1e-11, "an 8-point zoom of a 6-term polynomial matches");
        check(maxAbsDiff(spectrum, direct) <= 1e-11, "the 8-bin zoom is reproducible");
        check(Math.abs(re(spectrum, 0) - referenceR) <= 1e-12 && Math.abs(im(spectrum, 0) - referenceI) <= 1e-12,
                "z_0 = A = 1 evaluates to the coefficient sum");
    }

    static void modularCztAgainstDirect() {
        Rng rng = new Rng(5865L);
        for (int n : new int[]{7, 17, 119}) {
            long[] x = new long[n];
            for (int i = 0; i < n; i++) x[i] = rng.nextMod(MOD);
            long[] fast = dftMod(x, n, false);
            long[] slow = dftModDirect(x, n, false);
            check(Arrays.equals(fast, slow), "modular Bluestein equals the O(n^2) DFT for n = " + n);
            long[] back = dftMod(fast, n, true);
            check(Arrays.equals(back, x), "the modular inverse DFT recovers the input for n = " + n);
            long sum = 0;
            for (long value : x) sum = (sum + value) % MOD;
            check(fast[0] == sum, "X_0 is the coefficient sum modulo p for n = " + n);
            long[] delta = new long[n];
            delta[0] = 1;
            long[] flatSpectrum = dftMod(delta, n, false);
            for (int k = 0; k < n; k++) check(flatSpectrum[k] == 1, "the delta has a flat modular spectrum at " + k);
            // Orthogonality of the length-n root, verified with the transform itself.
            long[] ones = new long[n];
            Arrays.fill(ones, 1);
            long[] dc = dftMod(ones, n, false);
            check(dc[0] == n % MOD, "the DC bin of a constant vector is n");
            for (int k = 1; k < n; k++) check(dc[k] == 0, "orthogonality zeroes bin " + k + " for n = " + n);
        }
        check(dftMod(new long[]{5, 9}, 1, false)[0] == 5, "the length-1 modular DFT is the identity");
    }

    static void modularCyclicProduct() {
        Rng rng = new Rng(5866L);
        int n = 119;
        long[] a = new long[60];
        long[] b = new long[60];
        for (int i = 0; i < 60; i++) {
            a[i] = rng.nextMod(MOD);
            b[i] = rng.nextMod(MOD);
        }
        long[] linear = schoolbook(a, b);
        check(linear.length == 119, "the planted operands multiply to exactly the cyclic length");
        long[] cyclic = cyclicMod(a, b, n);
        check(Arrays.equals(cyclic, linear), "the length-119 cyclic product equals the linear product");
        long[] longer = schoolbook(new long[]{1, 2, 3, 4, 5, 6}, new long[]{7, 8, 9});
        check(longer.length == 8, "the wrap instance is short enough to fold by hand");
        long[] folded = cyclicMod(new long[]{1, 2, 3, 4, 5, 6}, new long[]{7, 8, 9}, 7);
        long[] expected = new long[7];
        for (int k = 0; k < longer.length; k++) expected[k % 7] = (expected[k % 7] + longer[k]) % MOD;
        check(Arrays.equals(folded, expected), "a shorter cyclic length folds the schoolbook result exactly");
        check(!Arrays.equals(Arrays.copyOf(longer, 7), folded),
                "with n = 7 < 8 the cyclic product genuinely wraps (asserted, not hidden)");
    }

    static void sizeConstraints() {
        // The complex CZT accepts 25 = 5^2; the modular one cannot, because 50 does not divide p - 1.
        check((MOD - 1) % 50 != 0, "50 does not divide p - 1, so the modular length 25 is impossible");
        Rng rng = new Rng(5867L);
        double[] x = randomComplex(25, rng, 1.0);
        double[] fast = dftAnyLength(x, 25);
        double angle = -2.0 * Math.PI / 25;
        double[] slow = cztDirect(x, 25, 1.0, 0.0, Math.cos(angle), Math.sin(angle), 25);
        check(maxAbsDiff(fast, slow) <= 1e-11, "the complex CZT handles a length-25 (square) transform");
        boolean threw = false;
        try {
            dftMod(new long[25], 25, false);
        } catch (IllegalArgumentException e) {
            threw = true;
        }
        check(threw, "the modular CZT rejects length 25 with an explanatory exception");
        for (int n : new int[]{7, 17, 119, 476}) {
            check((MOD - 1) % (2L * n) == 0, "2n divides p-1 for the supported modular length " + n);
        }
        check(nextPow2(3 * 119 - 2) == 512, "n = 119 needs a 512-point NTT");
        check(nextPow2(3 * 476 - 2) == 2048, "n = 476 needs a 2048-point NTT");
        check(nextPow2(3 * 2796203 - 2) == (1 << 23) && nextPow2(3 * 2796204 - 2) == (1 << 24),
                "the modular CZT still fits one 2^23-point NTT at n = 2796203 and needs 2^24 beyond it, "
                        + "so 2796203 is the modular length ceiling while the complex path is limited only "
                        + "by memory");
        double[] tiny = dftAnyLength(new double[]{3.0, 0.0}, 1);
        check(Math.abs(re(tiny, 0) - 3.0) <= 1e-12, "a length-1 complex transform is the identity");
        double[] repeated = dftAnyLength(new double[]{3.0, 0.0}, 1);
        check(Arrays.equals(tiny, repeated), "the transform is reproducible");
    }

